#!/usr/bin/env node
// Generates snapback/shared/station-art.gen.mjs from assets/station-art/*.svg.
//
// The hand-drawn scenes (ENG-23684; assets/station-art/README.md) ship three
// scenes per station as standalone SVG files. Surfaces need them as inline SVG
// markup for the Contract `image svgSource=` attribute (the DOM mirror blocks
// data: URIs on `src=`), so this script inlines all scenes into one generated
// module keyed by station id, scenes ordered 1..3. The surface picks the scene
// by epoch day (ENG-23719: the art rotates day by day).
//
// Run: node demos/all-aboard/scripts/gen-station-art.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const artDir = resolve(here, '..', 'assets', 'station-art');
const outPath = resolve(here, '..', 'snapback', 'shared', 'station-art.gen.mjs');

const files = readdirSync(artDir).filter((f) => /^[a-z0-9-]+-[123]\.svg$/.test(f)).sort();
if (files.length === 0) throw new Error(`no station art found in ${artDir}`);

const scenesByStation = new Map();
for (const file of files) {
  const match = /^(.*)-([123])\.svg$/.exec(file);
  const stationId = match[1];
  const scene = Number(match[2]);
  const svg = readFileSync(join(artDir, file), 'utf8').trim();
  if (!svg.startsWith('<svg')) throw new Error(`${file} does not start with <svg`);
  if (!scenesByStation.has(stationId)) scenesByStation.set(stationId, []);
  scenesByStation.get(stationId)[scene - 1] = svg;
}

for (const [stationId, scenes] of scenesByStation) {
  const missing = [1, 2, 3].filter((n) => !scenes[n - 1]);
  if (missing.length) throw new Error(`${stationId} is missing scene(s) ${missing.join(', ')}`);
}

const entries = [...scenesByStation.entries()]
  .map(([stationId, scenes]) =>
    `  ${JSON.stringify(stationId)}: [\n${scenes.map((s) => `    ${JSON.stringify(s)},`).join('\n')}\n  ],`)
  .join('\n');

const banner =
  `// @generated by demos/all-aboard/scripts/gen-station-art.mjs — do NOT edit by hand.\n` +
  `//   Regenerate: node demos/all-aboard/scripts/gen-station-art.mjs\n` +
  `// Hand-drawn station scenes (ENG-23684), three per station, inlined as SVG\n` +
  `// markup for the Contract image svgSource= attribute. Scene order matches the\n` +
  `// -1/-2/-3 filenames; see assets/station-art/README.md for the scene key.\n\n`;

writeFileSync(outPath, `${banner}export const STATION_ART_SCENES = {\n${entries}\n};\n`);
console.log(`wrote ${outPath}: ${scenesByStation.size} stations, ${files.length} scenes`);
