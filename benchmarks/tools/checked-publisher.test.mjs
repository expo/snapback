test('sanitizer retains private originals and emits only normalized public metadata', () => {
  const temporary = mkdtempSync(join(tmpdir(), 'snapback-llp0197-test-'));
  try {
    const keyFile = join(temporary, 'hmac.key');
    writeFileSync(keyFile, '0123456789abcdef0123456789abcdef', { mode: 0o600 });
    chmodSync(keyFile, 0o600);
    const privateStore = join(temporary, 'private-store');
    const rawTrace = fixtureJson('sanitizer/raw-safe.json');
    const publicTrace = sanitizeTrace({ root: ROOT, rawTrace, privateStore, keyFile });

    assert.deepEqual(publicTrace, fixtureJson('pass/evidence/public-trace.json'));
    assert.equal(publicTrace.reviewRequired, true);
    assert.equal(publicTrace.invocations.length, 1);
    const invocation = publicTrace.invocations[0];
    assert.equal(invocation.actionClass, 'proof-command');
    assert.equal(invocation.toolName, 'exec_command');
    assert.equal(invocation.resultStatus, 'success');
    assert.equal(invocation.timing.durationMs, 1250);
    assert.match(invocation.evidenceId, /^ev_[a-f0-9]{32}$/);
    assert.match(invocation.integrityCommitment, /^hmac-sha256:[a-f0-9]{64}$/);
    assert.equal(Object.hasOwn(invocation, 'arguments'), false);
    assert.equal(Object.hasOwn(invocation, 'transcript'), false);
    assert.deepEqual(invocation.redactions.map((item) => item.reasonCode), [
      'PRIVATE_ORIGINAL',
      'PRIVATE_TOOL_ARGUMENT',
      'PRIVATE_TRANSCRIPT',
    ]);

    const originalPath = join(privateStore, 'evidence', invocation.evidenceId, 'original.json');
    const privateOriginal = JSON.parse(readFileSync(originalPath, 'utf8'));
    assert.deepEqual(privateOriginal, rawTrace.invocations[0]);
    assert.equal(statSync(originalPath).mode & 0o077, 0);
    assert.doesNotMatch(JSON.stringify(publicTrace), /not-a-real-secret|Synthetic transcript/);
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
});

