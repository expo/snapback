#!/usr/bin/env node

import { existsSync, readFileSync, realpathSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { formatFailure } from './lib/failure.mjs';
import { buildCheckedPublication } from './lib/publisher.mjs';

const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)));

function usage() {
  return 'usage: node benchmarks/tools/publish.mjs --manifest <repo-relative.json> --output <repo-relative.md> [--check]\n';
}

function option(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : process.argv[index + 1];
}

function insideRoot(path) {
  const rel = relative(realpathSync(ROOT), realpathSync(dirname(path)));
  return rel === '' || (!rel.startsWith(`..${sep}`) && rel !== '..' && !rel.startsWith(sep));
}

try {
  const manifestPath = option('--manifest');
  const outputPath = option('--output');
  const check = process.argv.includes('--check');
  if (!manifestPath || !outputPath) throw new Error(usage().trim());
  if (outputPath.startsWith('/') || outputPath.split('/').includes('..') || !outputPath.endsWith('.md')) {
    throw new Error('--output must be a repository-relative Markdown path');
  }
  const result = buildCheckedPublication({ root: ROOT, manifestPath, requireCommitted: true });
  const absoluteOutput = resolve(ROOT, outputPath);
  if (!insideRoot(absoluteOutput)) throw new Error('--output parent resolves outside the repository');
  if (check) {
    if (!existsSync(absoluteOutput) || readFileSync(absoluteOutput, 'utf8') !== result.markdown) {
      process.stderr.write(`BENCHMARK_PUBLISHER_GENERATED_OUTPUT_DRIFT: ${outputPath} is missing or stale\n`);
      process.exitCode = 1;
    } else {
      process.stdout.write(`[checked-publisher] PASS ${outputPath}\n`);
    }
  } else {
    if (existsSync(absoluteOutput)
        && !readFileSync(absoluteOutput, 'utf8').startsWith('<!-- GENERATED by benchmarks/tools/publish.mjs;')) {
      throw new Error(`refusing to overwrite non-generated file: ${outputPath}`);
    }
    const temporary = resolve(dirname(absoluteOutput), `.${outputPath.split('/').at(-1)}.${process.pid}.tmp`);
    try {
      writeFileSync(temporary, result.markdown, { encoding: 'utf8', mode: 0o644 });
      renameSync(temporary, absoluteOutput);
    } finally {
      if (existsSync(temporary)) unlinkSync(temporary);
    }
    process.stdout.write(`[checked-publisher] wrote ${outputPath}\n`);
  }
} catch (error) {
  process.stderr.write(`${formatFailure(error)}\n`);
  process.exitCode = 1;
}
