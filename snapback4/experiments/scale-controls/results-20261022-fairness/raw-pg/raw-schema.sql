BEGIN;
CREATE TABLE users (id bigint PRIMARY KEY, sent bigint NOT NULL DEFAULT 0);
CREATE TABLE rooms (id bigint PRIMARY KEY, total bigint NOT NULL DEFAULT 0);
CREATE TABLE memberships (
  room bigint NOT NULL REFERENCES rooms, principal bigint NOT NULL REFERENCES users,
  last_read bigint NOT NULL DEFAULT 0, PRIMARY KEY (room, principal)
);
CREATE INDEX memberships_principal_room ON memberships (principal, room) INCLUDE (last_read);
CREATE TABLE messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room bigint NOT NULL REFERENCES rooms, sender bigint NOT NULL REFERENCES users,
  at bigint NOT NULL, body text NOT NULL CHECK (octet_length(body) <= 4000)
);
CREATE INDEX messages_room_time ON messages (room, at DESC, id DESC);
CREATE TABLE counters (
  id bigint PRIMARY KEY, owner_id bigint REFERENCES users,
  room bigint NOT NULL REFERENCES rooms, n bigint NOT NULL DEFAULT 0
) WITH (fillfactor=70);
CREATE FUNCTION maintain_message() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE rooms SET total = total + 1 WHERE id = NEW.room;
  UPDATE users SET sent = sent + 1 WHERE id = NEW.sender;
  RETURN NEW;
END $$;
CREATE TRIGGER message_totals AFTER INSERT ON messages
FOR EACH ROW EXECUTE FUNCTION maintain_message();
-- Writes run as s1fr_app, which cannot modify these maintained columns.
GRANT SELECT ON users, rooms, memberships, messages, counters TO s1fr_app;
GRANT INSERT (room,sender,at,body) ON messages TO s1fr_app;
GRANT UPDATE (n) ON counters TO s1fr_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO s1fr_app;
ALTER FUNCTION maintain_message() SECURITY DEFINER SET search_path=public,pg_catalog;
REVOKE ALL ON FUNCTION maintain_message() FROM PUBLIC;

COMMIT;
