// @ref LLP 3000.013#6 — exported static files are the offline shell; API and replica data never enter this cache.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, lstat } from "node:fs/promises";
import { join, resolve } from "node:path";

const workerName = "snapback4-sw.js";
const marker = /<!-- snapback4:web-shell -->[\s\S]*?<!-- \/snapback4:web-shell -->\n?/g;
const escapeScript = value => JSON.stringify(value).replace(/</g, "\\u003c");

export async function webShell(directory, base = "/") {
  if (!/^\/(?:[A-Za-z0-9._~-]+\/)*$/.test(base) || base.split("/").some(part => part === "." || part === "..")) throw Error("web-shell: --base must be an absolute directory such as / or /chat/");
  const root = resolve(directory);
  const files = [];
  async function walk(relative = "") {
    for (const entry of (await readdir(join(root, relative), { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
      const name = relative ? `${relative}/${entry.name}` : entry.name;
      if (entry.isSymbolicLink()) throw Error(`web-shell: symlink ${name} is not a static exported file`);
      if (entry.isDirectory()) await walk(name);
      else if (entry.isFile() && name !== workerName) files.push(name);
      else if (!entry.isFile()) throw Error(`web-shell: ${name} is not a static exported file`);
    }
  }
  if (!(await lstat(root)).isDirectory()) throw Error("web-shell: expected an exported application directory");
  await walk();
  if (!files.includes("index.html")) throw Error("web-shell: export index.html before running snapback4 web-shell <dir>");
  if (files.includes(workerName)) throw Error("web-shell: reserved service worker filename");
  const registration = `<!-- snapback4:web-shell -->\n<script>if ('serviceWorker' in navigator) { window.addEventListener('load', function () { navigator.serviceWorker.register(${escapeScript(base + workerName)}, { scope: ${escapeScript(base)}, updateViaCache: 'none' }).catch(function (error) { console.error('Offline shell could not be installed', error); }); }); }</script>\n<!-- /snapback4:web-shell -->\n`;
  const content = new Map();
  for (const name of files) {
    let bytes = await readFile(join(root, name));
    if (/\.html$/i.test(name)) {
      const html = bytes.toString("utf8").replace(marker, "");
      bytes = Buffer.from(/<\/body\s*>/i.test(html) ? html.replace(/<\/body\s*>/i, registration + "$&") : html + registration);
    }
    content.set(name, bytes);
  }
  // Hash framed paths and the final HTML, so changing registration/base also
  // changes the cache. The worker itself is excluded to make reruns identical.
  const hash = createHash("sha256").update("snapback4-web-shell-v1\0" + base);
  for (const [name, bytes] of content) hash.update(JSON.stringify([name, bytes.length])).update(bytes);
  const prefix = `snapback4-shell:${encodeURIComponent(base)}:`;
  const cache = prefix + hash.digest("hex");
  const paths = files.map(name => base + name.split("/").map(encodeURIComponent).join("/"));
  const source = worker({ prefix, cache, paths, base });
  for (const [name, bytes] of content) if (/\.html$/i.test(name)) await writeFile(join(root, name), bytes);
  await writeFile(join(root, workerName), source);
  return { files: files.length, cache, base };
}

function worker({ prefix, cache, paths, base }) {
  return `// Generated by snapback4 web-shell. Deploy with this export's static files.
const PREFIX = ${JSON.stringify(prefix)};
const CACHE = ${JSON.stringify(cache)};
const PATHS = ${JSON.stringify(paths)};
const BASE = ${JSON.stringify(base)};
const ENTRY = BASE + "index.html";
const url = path => new URL(path, self.location.origin).href;
self.addEventListener("install", event => event.waitUntil((async () => {
  const existed = await caches.has(CACHE);
  const cache = await caches.open(CACHE);
  try {
    for (const path of PATHS) {
      const response = await fetch(new Request(url(path), { credentials: "omit", cache: "reload", redirect: "error" }));
      if (!response.ok || response.type !== "basic") throw Error("Shell asset unavailable: " + path);
      await cache.put(url(path), response);
    }
  } catch (error) { if (!existed) await caches.delete(CACHE); throw error; }
})()));
// Wait for old tabs to close: never delete assets from their running build.
self.addEventListener("activate", event => event.waitUntil((async () => {
  for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
})()));
self.addEventListener("fetch", event => {
  const request = event.request, address = new URL(request.url);
  if (request.method !== "GET" || address.origin !== self.location.origin || request.headers.has("authorization")) return;
  const navigation = request.mode === "navigate" && address.pathname.startsWith(BASE);
  const asset = !navigation && !address.search && PATHS.includes(address.pathname);
  if (!navigation && !asset) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (navigation) {
      // HTML and lazy assets must belong to the active build, even online.
      // A waiting worker switches both together after the old tabs close.
      const path = address.pathname;
      const pages = path.endsWith("/") ? [path + "index.html"] : [path, path + ".html", path + "/index.html"];
      for (const page of [...pages, ENTRY]) {
        const response = await cache.match(url(page));
        if (response) return response;
      }
      return Response.error();
    }
    return (await cache.match(url(address.pathname))) || fetch(request);
  })());
});
`;
}

export async function runWebShell(args) {
  const directory = args.shift();
  let base = "/";
  if (args[0] === "--base" && args.length === 2) base = args[1];
  else if (args.length === 1 && args[0].startsWith("--base=")) base = args[0].slice(7);
  else if (args.length) throw Error("usage: snapback4 web-shell <dir> [--base /]");
  if (!directory || directory.startsWith("--")) throw Error("usage: snapback4 web-shell <dir> [--base /]");
  const result = await webShell(directory, base);
  console.log(`web-shell: ${result.files} files at ${result.base}; wrote ${workerName}`);
}
