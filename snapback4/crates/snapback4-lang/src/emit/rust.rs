//! The native module's types, by inference (LLP 3000.005): one generated
//! Rust file with a constant per table, index and maintain, and a `serde`
//! struct per table whose fields are the columns. Built by `check` into
//! `snapback/generated/native.rs`, never committed; the app includes it.

use crate::bind::Bound;
use snapback4_core::schema::ColumnType;
use std::collections::{BTreeMap, BTreeSet};

pub fn rust(bound: &Bound) -> String {
    let projection = bound.schema.public_projection();
    let schema = &projection;
    let mut out = String::new();
    out.push_str("// Generated by snapback4 from snapback/*.q. Do not edit; edit the schema.\n");
    out.push_str("// In snapback/native/src/lib.rs: `mod schema { include!(\"../../generated/native.rs\"); } use schema::*;`\n\n");
    let maintained = |name: &str| schema.maintain_for(name).is_some();
    let table_constants = unique_names(schema.tables.keys().filter(|name| !maintained(name)), screaming);
    let maintain_constants = unique_names(schema.tables.keys().filter(|name| maintained(name)), screaming);
    let index_modules = unique_names(schema.tables.keys().filter(|name| !maintained(name)), module);
    let structs = unique_names(schema.tables.keys(), type_name);
    out.push_str("/// Table names, for `Ctx` calls.\n#[allow(dead_code)]\npub mod tables {\n");
    for name in schema.tables.keys().filter(|name| !maintained(name)) {
        out.push_str(&format!("    pub const {}: &str = {};\n", table_constants[name], string_literal(name)));
    }
    out.push_str("}\n\n/// Maintained aggregates, for `Ctx::maintained`.\n#[allow(dead_code)]\npub mod maintains {\n");
    for name in schema.tables.keys().filter(|name| maintained(name)) {
        out.push_str(&format!("    pub const {}: &str = {};\n", maintain_constants[name], string_literal(name)));
    }
    out.push_str("}\n\n/// Index names, per table.\n#[allow(dead_code)]\npub mod indexes {\n");
    for (name, table) in schema.tables.iter().filter(|(name, _)| !maintained(name)) {
        out.push_str(&format!("    pub mod {} {{\n", index_modules[name]));
        let constants = unique_names(table.indexes.keys(), screaming);
        for index in table.indexes.keys() {
            out.push_str(&format!("        pub const {}: &str = {};\n", constants[index], string_literal(index)));
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    for (name, table) in &schema.tables {
        out.push_str(&format!("\n/// A row of `{name}`{}.\n", if maintained(name) { " (a maintained aggregate: the group's columns and `value`)" } else { "" }));
        out.push_str("#[allow(dead_code)]\n#[derive(Clone, Debug, Default, PartialEq, snapback4_native::serde::Serialize, snapback4_native::serde::Deserialize)]\n#[serde(crate = \"snapback4_native::serde\")]\n");
        out.push_str(&format!("pub struct {} {{\n", structs[name]));
        let reserved: &[&str] = if table.columns.contains_key("id") { &[] } else { &["id"] };
        let fields = unique_names_reserved(table.columns.keys().filter(|name| !table.recorded.contains_key(*name) && !snapback4_core::schema::timeline::is_slot(name)), field_name, reserved);
        if !table.columns.contains_key("id") {
            out.push_str("    pub id: String,\n");
        }
        for (column, kind) in table.columns.iter().filter(|(name, _)| !table.recorded.contains_key(*name) && !snapback4_core::schema::timeline::is_slot(name)) {
            let field = &fields[column];
            if field != column {
                out.push_str(&format!("    #[serde(rename = {})]\n", string_literal(column)));
            }
            if kind.is_optional() {
                out.push_str("    #[serde(default)]\n");
            }
            out.push_str(&format!("    pub {field}: {},\n", rust_type(kind)));
        }
        out.push_str("}\n");
    }
    let write_names = unique_names_reserved(schema.visible_tables().filter(|(_,t)| !t.maintained.is_empty()).map(|(name,_)|name), |name|format!("{}Write",type_name(name)), &structs.values().map(String::as_str).collect::<Vec<_>>());
    for (name, table) in schema.visible_tables().filter(|(_,t)| !t.maintained.is_empty()) {
        out.push_str(&format!("\n/// The id-bearing result of a write to `{name}`; read the row for maintained fields.\n#[derive(Clone, Debug, Default, PartialEq, snapback4_native::serde::Serialize, snapback4_native::serde::Deserialize)]\n#[serde(crate = \"snapback4_native::serde\")]\npub struct {} {{\n",write_names[name]));
        let fields = unique_names(table.columns.keys().filter(|n| !table.recorded.contains_key(*n) && !snapback4_core::schema::timeline::is_slot(n) && !table.maintained.contains_key(*n)),field_name);
        for (column,field) in fields { out.push_str(&format!("    #[serde(rename = {})]\n    pub {field}: {},\n",string_literal(&column),rust_type(&table.columns[&column]))); }
        out.push_str("}\n");
    }
    out
}

fn rust_type(kind: &ColumnType) -> String {
    match kind {
        ColumnType::Id | ColumnType::Principal | ColumnType::Ref { .. } | ColumnType::Text { .. } | ColumnType::Enum { .. } | ColumnType::Bytes { .. } => "String".into(),
        ColumnType::Int | ColumnType::Time | ColumnType::Decimal { .. } | ColumnType::Money { .. } => "i64".into(),
        ColumnType::Bool => "bool".into(),
        ColumnType::Json { .. } | ColumnType::Image { .. } | ColumnType::Video { .. } => "snapback4_native::Json".into(),
        ColumnType::Optional(inner) => format!("Option<{}>", rust_type(inner)),
        ColumnType::List { of, .. } => format!("Vec<{}>", rust_type(of)),
    }
}

/// `promptId` → `prompt_id`; a keyword is raw (`r#type`).
fn field_name(column: &str) -> String {
    let name = snake(column);
    const KEYWORDS: &[&str] = &["as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen"];
    if matches!(name.as_str(), "self" | "Self" | "super" | "crate") {
        format!("{name}_")
    } else if KEYWORDS.contains(&name.as_str()) {
        format!("r#{name}")
    } else {
        name
    }
}

fn module(name: &str) -> String {
    field_name(name)
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    let mut previous_lower = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            if previous_lower {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
            previous_lower = false;
        } else if c.is_ascii_alphanumeric() {
            out.push(c);
            previous_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        } else {
            out.push('_');
            previous_lower = false;
        }
    }
    if out.trim_matches('_').is_empty() { return "item".into(); }
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

fn screaming(name: &str) -> String {
    snake(name).to_ascii_uppercase()
}

fn type_name(name: &str) -> String {
    let mut name: String = snake(name).split('_').filter(|part| !part.is_empty()).map(|part| {
        let mut chars = part.chars();
        match chars.next() {
            Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
            None => String::new(),
        }
    }).collect();
    if name.chars().next().is_some_and(|c| c.is_ascii_digit()) { name.insert_str(0, "Row"); }
    match name.as_str() {
        "Self" => "SelfRow".into(),
        "String" | "Option" | "Vec" => format!("{name}Row"),
        _ => name,
    }
}

/// Allocate valid identifiers in one Rust namespace. An exact conventional
/// spelling wins its base; other normalization collisions get stable suffixes.
fn unique_names<'a>(names: impl Iterator<Item = &'a String>, normalize: fn(&str) -> String) -> BTreeMap<String, String> {
    unique_names_reserved(names, normalize, &[])
}

fn unique_names_reserved<'a>(names: impl Iterator<Item = &'a String>, normalize: fn(&str) -> String, reserved: &[&str]) -> BTreeMap<String, String> {
    let mut pending: Vec<(String, String)> = names.map(|name| (name.clone(), normalize(name))).collect();
    pending.sort_by(|(left, left_base), (right, right_base)| left_base.cmp(right_base).then_with(|| (left != left_base).cmp(&(right != right_base))).then_with(|| left.cmp(right)));
    let mut used: BTreeSet<String> = reserved.iter().map(|name| (*name).to_owned()).collect();
    let mut out = BTreeMap::new();
    for (original, base) in pending {
        let mut candidate = base.clone();
        let mut suffix = 2;
        while !used.insert(candidate.clone()) {
            candidate = if let Some(raw) = base.strip_prefix("r#") { format!("{raw}_{suffix}") } else { format!("{base}_{suffix}") };
            suffix += 1;
        }
        out.insert(original, candidate);
    }
    out
}

fn string_literal(value: &str) -> String {
    serde_json::to_string(value).expect("strings always serialize")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_follow_rust_conventions() {
        assert_eq!(snake("promptId"), "prompt_id");
        assert_eq!(snake("aiJobs"), "ai_jobs");
        assert_eq!(snake("byConversationPrincipalRole"), "by_conversation_principal_role");
        assert_eq!(type_name("messageCounts"), "MessageCounts");
        assert_eq!(type_name("posts"), "Posts");
        assert_eq!(screaming("postScore"), "POST_SCORE");
        assert_eq!(field_name("type"), "r#type");
        assert_eq!(field_name("self"), "self_");
        assert_eq!(field_name("_"), "item");
        assert_eq!(type_name("Self"), "SelfRow");
        assert_eq!(type_name("_1"), "Row1");
        let synthetic_collision = ["ID".to_owned()];
        assert_eq!(unique_names_reserved(synthetic_collision.iter(), field_name, &["id"])["ID"], "id_2");
    }

    #[test]
    fn a_table_becomes_a_struct_and_its_names_constants() {
        let bound = crate::compile(&[("schema.q".into(), "table posts:\n  promptId: id\n  provider: text <=30 ?\n  at: time\n  by byTime: at, id\n  read <- allow\n  insert <- allow\n  update <- deny\n  delete <- deny\n\nmaintain postCount: count posts by promptId\n  read <- allow\n".into())]);
        assert!(bound.diagnostics.is_empty(), "{:?}", bound.diagnostics);
        let text = rust(&bound);
        assert!(text.contains("pub const POSTS: &str = \"posts\";"), "{text}");
        assert!(text.contains("pub const POST_COUNT: &str = \"postCount\";"), "{text}");
        assert!(text.contains("pub const BY_TIME: &str = \"byTime\";"), "{text}");
        assert!(text.contains("pub struct Posts {"), "{text}");
        assert!(text.contains("#[serde(rename = \"promptId\")]\n    pub prompt_id: String,"), "{text}");
        assert!(text.contains("#[serde(default)]\n    pub provider: Option<String>,"), "{text}");
        assert!(text.contains("pub at: i64,"), "{text}");
    }

    #[test]
    fn colliding_and_reserved_quarry_names_emit_compilable_unique_rust() {
        let bound = crate::compile(&[("schema.q".into(), r#"
table fooBar:
  fooBar: text <=10
  foo_bar: text <=10
  Self: text <=10
  _: text <=10
  type: text <=10
  self: text <=10
  by byFooBar: fooBar, id
  by by_foo_bar: foo_bar, id
  public 'test'
table foo_bar:
  public 'test'
table Self:
  public 'test'
table _:
  public 'test'
table String:
  public 'test'
table _1:
  public 'test'
"#.into())]);
        assert!(bound.diagnostics.is_empty(), "{:?}", bound.diagnostics);
        let text = rust(&bound);
        assert!(text.contains("pub struct SelfRow"), "{text}");
        assert!(text.contains("pub struct StringRow"), "{text}");
        assert!(text.contains("pub struct Row1"), "{text}");
        for original in ["fooBar", "Self", "_", "type", "self"] { assert!(text.contains(&format!("#[serde(rename = {})]", string_literal(original))), "{original}: {text}"); }

        // Remove only external serde syntax; rustc then checks every generated
        // identifier and namespace collision directly.
        let compilable = text.lines().filter(|line| !line.trim_start().starts_with("#[serde")).map(|line| if line.starts_with("#[derive(") { "#[derive(Clone, Debug, Default, PartialEq)]" } else { line }).collect::<Vec<_>>().join("\n");
        let output = std::env::temp_dir().join(format!("snapback4-generated-{}-{}.rmeta", std::process::id(), std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()));
        let mut child = std::process::Command::new("rustc").args(["--crate-name", "generated", "--crate-type", "lib", "--edition=2024", "--emit=metadata", "-o"]).arg(&output).arg("-").stdin(std::process::Stdio::piped()).stderr(std::process::Stdio::piped()).spawn().expect("rustc");
        use std::io::Write as _;
        child.stdin.take().unwrap().write_all(compilable.as_bytes()).unwrap();
        let result = child.wait_with_output().unwrap();
        let _ = std::fs::remove_file(output);
        assert!(result.status.success(), "{}\n{text}", String::from_utf8_lossy(&result.stderr));
    }
}
