//! The native module's types, by inference (LLP 3000.005): one generated
//! Rust file with a constant per table, index and maintain, and a `serde`
//! struct per table whose fields are the columns. Built by `check` into
//! `snapback/generated/native.rs`, never committed; the app includes it.

use crate::bind::Bound;
use snapback4_core::schema::ColumnType;

pub fn rust(bound: &Bound) -> String {
    let schema = &bound.schema;
    let mut out = String::new();
    out.push_str("// Generated by snapback4 from snapback/*.q. Do not edit; edit the schema.\n");
    out.push_str("// In snapback/native/src/lib.rs: `mod schema { include!(\"../../generated/native.rs\"); } use schema::*;`\n\n");
    let maintained = |name: &str| schema.maintain_for(name).is_some();
    out.push_str("/// Table names, for `Ctx` calls.\n#[allow(dead_code)]\npub mod tables {\n");
    for name in schema.tables.keys().filter(|name| !maintained(name)) {
        out.push_str(&format!("    pub const {}: &str = {};\n", screaming(name), string_literal(name)));
    }
    out.push_str("}\n\n/// Maintained aggregates, for `Ctx::maintained`.\n#[allow(dead_code)]\npub mod maintains {\n");
    for name in schema.tables.keys().filter(|name| maintained(name)) {
        out.push_str(&format!("    pub const {}: &str = {};\n", screaming(name), string_literal(name)));
    }
    out.push_str("}\n\n/// Index names, per table.\n#[allow(dead_code)]\npub mod indexes {\n");
    for (name, table) in schema.tables.iter().filter(|(name, _)| !maintained(name)) {
        out.push_str(&format!("    pub mod {} {{\n", module(name)));
        for index in table.indexes.keys() {
            out.push_str(&format!("        pub const {}: &str = {};\n", screaming(index), string_literal(index)));
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    for (name, table) in &schema.tables {
        out.push_str(&format!("\n/// A row of `{name}`{}.\n", if maintained(name) { " (a maintained aggregate: the group's columns and `value`)" } else { "" }));
        out.push_str("#[allow(dead_code)]\n#[derive(Clone, Debug, Default, PartialEq, snapback4_native::serde::Serialize, snapback4_native::serde::Deserialize)]\n#[serde(crate = \"snapback4_native::serde\")]\n");
        out.push_str(&format!("pub struct {} {{\n", pascal(name)));
        if !table.columns.contains_key("id") {
            out.push_str("    pub id: String,\n");
        }
        for (column, kind) in &table.columns {
            let field = field_name(column);
            if field != *column {
                out.push_str(&format!("    #[serde(rename = {})]\n", string_literal(column)));
            }
            if kind.is_optional() {
                out.push_str("    #[serde(default)]\n");
            }
            out.push_str(&format!("    pub {field}: {},\n", rust_type(kind)));
        }
        out.push_str("}\n");
    }
    out
}

fn rust_type(kind: &ColumnType) -> String {
    match kind {
        ColumnType::Id | ColumnType::Principal | ColumnType::Ref { .. } | ColumnType::Text { .. } | ColumnType::Enum { .. } | ColumnType::Bytes { .. } => "String".into(),
        ColumnType::Int | ColumnType::Time | ColumnType::Decimal { .. } | ColumnType::Money { .. } => "i64".into(),
        ColumnType::Bool => "bool".into(),
        ColumnType::Json { .. } | ColumnType::Image { .. } | ColumnType::Video { .. } => "snapback4_native::Json".into(),
        ColumnType::Optional(inner) => format!("Option<{}>", rust_type(inner)),
        ColumnType::List { of, .. } => format!("Vec<{}>", rust_type(of)),
    }
}

/// `promptId` → `prompt_id`; a keyword is raw (`r#type`).
fn field_name(column: &str) -> String {
    let name = snake(column);
    const KEYWORDS: &[&str] = &["as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen"];
    if matches!(name.as_str(), "self" | "Self" | "super" | "crate") {
        format!("{name}_")
    } else if KEYWORDS.contains(&name.as_str()) {
        format!("r#{name}")
    } else {
        name
    }
}

fn module(name: &str) -> String {
    field_name(name)
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    let mut previous_lower = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            if previous_lower {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
            previous_lower = false;
        } else if c.is_ascii_alphanumeric() {
            out.push(c);
            previous_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        } else {
            out.push('_');
            previous_lower = false;
        }
    }
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

fn screaming(name: &str) -> String {
    snake(name).to_ascii_uppercase()
}

fn pascal(name: &str) -> String {
    snake(name).split('_').filter(|part| !part.is_empty()).map(|part| {
        let mut chars = part.chars();
        match chars.next() {
            Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
            None => String::new(),
        }
    }).collect()
}

fn string_literal(value: &str) -> String {
    serde_json::to_string(value).expect("strings always serialize")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_follow_rust_conventions() {
        assert_eq!(snake("promptId"), "prompt_id");
        assert_eq!(snake("aiJobs"), "ai_jobs");
        assert_eq!(snake("byConversationPrincipalRole"), "by_conversation_principal_role");
        assert_eq!(pascal("messageCounts"), "MessageCounts");
        assert_eq!(pascal("posts"), "Posts");
        assert_eq!(screaming("postScore"), "POST_SCORE");
        assert_eq!(field_name("type"), "r#type");
        assert_eq!(field_name("self"), "self_");
    }

    #[test]
    fn a_table_becomes_a_struct_and_its_names_constants() {
        let bound = crate::compile(&[("schema.q".into(), "table posts:\n  promptId: id\n  provider: text <=30 ?\n  at: time\n  by byTime: at, id\n  read <- allow\n  insert <- allow\n  update <- deny\n  delete <- deny\n\nmaintain postCount: count posts by promptId\n  read <- allow\n".into())]);
        assert!(bound.diagnostics.is_empty(), "{:?}", bound.diagnostics);
        let text = rust(&bound);
        assert!(text.contains("pub const POSTS: &str = \"posts\";"), "{text}");
        assert!(text.contains("pub const POST_COUNT: &str = \"postCount\";"), "{text}");
        assert!(text.contains("pub const BY_TIME: &str = \"byTime\";"), "{text}");
        assert!(text.contains("pub struct Posts {"), "{text}");
        assert!(text.contains("#[serde(rename = \"promptId\")]\n    pub prompt_id: String,"), "{text}");
        assert!(text.contains("#[serde(default)]\n    pub provider: Option<String>,"), "{text}");
        assert!(text.contains("pub at: i64,"), "{text}");
    }
}
