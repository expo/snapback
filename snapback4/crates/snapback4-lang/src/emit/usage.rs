//! App-specific, compiled-example reading packet. It travels with every API emitter.
// @ref LLP 3000.037.000#15-schema-specific-client-usage-gen1 — generated examples, bounded per operation, no authority inference.
use super::{args_ts_with_aliases, property, string_literal, ty_ts};
use crate::{Bound, types::Ty};
use snapback4_core::ir::{BinaryOp, Expr, Input, ProgramKind, Stmt, UnaryOp};
use std::collections::BTreeSet;

pub const START: &str = "/* Client usage — generated from this app's checked schema.\n";
pub const END: &str = "End client usage. */";

pub fn markdown(bound: &Bound, spanning: bool) -> String {
    let mut out = String::from(
        "# This app's client usage\n\nGenerated by check/dev; edit snapback/*.q, never this packet.\n",
    );
    if spanning {
        out.push_str("Compatibility: shapes below describe the current schema only. Earlier releases can omit new fields or return older enum values. Use ArgsOf/ResultOf and Rows from this spanning api.ts as the authoritative cross-release types.\n\n");
    }
    out.push_str("Use the existing app.client under AppProvider, or the session client below under <SnapbackProvider client={client}>. Hooks run at component/custom-hook top level; invoke returned writes in handlers. Signup grants no role: provision the signed-in principal through your authorized app operation/operator. Roles are stored rows, never client options. Each Session line quotes caller guards, not a complete authorization analysis; row/field rules still apply.\n\n```ts\nimport { api, type Rows } from './api';\nimport type { ArgsOf, ResultOf, Session, Cursor, UploadOptions } from 'snapback4/contract';\nimport { createClient } from 'snapback4/client';\nimport { useQuery, usePage, useFollowing, useMutation, useAction } from 'snapback4/react';\n");
    if bound.schema.auth.password {
        out.push_str("import { login } from 'snapback4/auth';\nasync function signIn(url: string, email: string, password: string) {\n  const signedIn = await login(url, email, password);\n  if (!signedIn.ok) throw new Error(signedIn.why.code);\n  return createClient({ url, session: signedIn.session });\n}\n");
    }
    out.push_str("declare const url: string, session: Session; // your server and current signed-in account\nconst client = createClient({ url, session });\nasync function uploadArgument(bytes: Blob, options?: UploadOptions) {\n  const uploaded = await client.upload(bytes, options);\n  if (!uploaded.ok) throw new Error(uploaded.why.code);\n  return { id: uploaded.asset.id };\n}\n```\n\nUploads: use uploadArgument(bytes) for image/video, or uploadArgument(bytes, {file: {type, name}}) for documents; pass its returned object to the asset argument. Upload separately per column. Service-only caller guards need a server-side client with its minted service token: createClient({url, token}); never expose it in a browser.\n\nRead: isReady(read) from snapback4/contract exposes data; denied reads have denied.code. Page hooks expose items/read/loadMore; plain query exposes next (pass unchanged to the cursor argument until null). Writes: failed has why.code; sent has result (replay can omit it); pending is not committed. Actions/signals have their own state; inspect the returned union. Infrastructure/auth/input/rule/meter/upload refusals can also occur; the per-operation codes below are declared guards, not an exhaustive runtime list.\n");
    let mut rows = BTreeSet::new();
    for p in &bound.programs {
        if p.program.kind != ProgramKind::Job {
            result_rows(&p.result, &mut rows);
        }
    }
    if !rows.is_empty() {
        out.push_str(
            "\nResult row fields (`?` means possibly hidden/absent; null is a separate value):\n",
        );
        for name in rows {
            if let Some(table) = bound.schema.table(&name) {
                let fields = table
                    .columns
                    .iter()
                    .filter(|(n, _)| {
                        n.as_str() != "$global"
                            && !table.engine_field(n)
                            && !snapback4_core::schema::timeline::is_slot(n)
                    })
                    .map(|(n, k)| {
                        format!(
                            "{}{}: {}",
                            property(n),
                            if table.read_optional(n) { "?" } else { "" },
                            compact_ty(&Ty::from_column(k))
                        )
                    })
                    .collect::<Vec<_>>()
                    .join("; ");
                out.push_str(&format!(
                    "- Rows[{}]: {{ {fields} }}\n",
                    string_literal(&name)
                ));
            } else if let Some(ty) = bound.view_types.get(&name) {
                out.push_str(&format!(
                    "- Rows[{}]: {}\n",
                    string_literal(&name),
                    ty_ts(ty)
                ));
            }
        }
    }
    for p in &bound.programs {
        let kind = p.program.kind;
        if kind == ProgramKind::Job {
            continue;
        }
        let short = p.program.name.rsplit('.').next().unwrap();
        // Bracket access handles every authored module/operation identifier, including __proto__.
        let path = if p.module == "schema" {
            format!("api[{}]", string_literal(short))
        } else {
            format!(
                "api[{}][{}]",
                string_literal(&p.module),
                string_literal(short)
            )
        };
        let fact = &bound.schema.operations[&p.program.name];
        let following = kind == ProgramKind::Query
            && snapback4_core::engine::following_history::projection::plan(
                &bound.schema,
                &p.program,
            )
            .is_some();
        let paged = !following
            && kind == ProgramKind::Query
            && p.args
                .iter()
                .any(|(n, t)| n == "c" && matches!(t, Ty::Optional(t) if **t == Ty::Cursor))
            && p.result.sequence().is_some();
        let hook = match kind {
            ProgramKind::Query if following => "useFollowing",
            ProgramKind::Query if paged => "usePage",
            ProgramKind::Query => "useQuery",
            ProgramKind::Mutation => "useMutation",
            ProgramKind::Action => "useAction",
            _ => unreachable!(),
        };
        let method = match kind {
            ProgramKind::Query => "query",
            ProgramKind::Mutation => "mutate",
            ProgramKind::Action => "act",
            _ => unreachable!(),
        };
        let guards = p
            .program
            .body
            .iter()
            .filter_map(|s| {
                if let Stmt::Require {
                    condition,
                    site: Some(site),
                    ..
                } = s
                {
                    if kind == ProgramKind::Action {
                        action_rule(condition).map(|text| format!("admission: {text}"))
                    } else {
                        bound
                            .refusal_sites
                            .get(&("$clause".into(), site.clone()))
                            .filter(|text| text.contains("viewer"))
                            .map(|text| text.trim().to_owned())
                    }
                } else {
                    None
                }
            })
            .collect::<Vec<_>>();
        let session = if guards.is_empty() {
            "caller/row policy is in the schema".into()
        } else {
            guards.join("; ")
        };
        let args = compact_args(&args_ts_with_aliases(&p.args, &p.program.arg_aliases));
        let result = compact_ty(&p.result);
        let codes = if fact.requires.is_empty() {
            "none".into()
        } else {
            fact.requires.join(", ")
        };
        let note = if fact.held {
            " Device-only: call on app.client with held facts; the online tier refuses E_QUERY_HELD."
        } else if following {
            " useFollowing owns exact online history (items/phase/code/hasMore/loadMore; offline uses inbox). Plain client.query below reads only the bounded inbox, not that exact-history session."
        } else {
            ""
        };
        let mut calls = format!("```ts\n{{\n  const operation = {path};\n");
        let args_type = "ArgsOf<typeof operation>";
        if kind == ProgramKind::Query {
            let hook_args = if paged {
                format!("Omit<{args_type}, 'c'>")
            } else {
                args_type.to_owned()
            };
            calls.push_str(&format!(
                "  function useExample(args: {hook_args}) {{ return {hook}(operation, args); }}\n"
            ));
        } else {
            calls.push_str(&format!("  function useExample() {{\n    const op = {hook}(operation);\n    return (args: {args_type}) => op.run(args);\n  }}\n"));
        }
        calls.push_str(&format!("  async function callExample(args: {args_type}) {{ return client.{method}(operation, args); }}\n}}\n```\n"));
        let header = format!(
            "\n## {} {}\n\nArgs: `{args}`. Result: `{result}`.\nSession: client uses this caller's credential; {session}.\nDeclared refusals: {codes}.{note}\n\n",
            kind.word(),
            p.program.name
        );
        // Avoid repeating huge literal domains/records/guard text in the reading
        // block. The full generated Ops types/JSDoc below retain every detail.
        // This is presentation only; never cap or drop operations/schema types.
        if header.len() + calls.len() > 1500
            || args.len() > 600
            || result.len() > 400
            || session.len() > 400
            || codes.len() > 240
        {
            let args = if args.len() <= 400 {
                args
            } else {
                "ArgsOf<typeof operation> (full shape: Ops below)".into()
            };
            let result = if result.len() <= 250 {
                result
            } else {
                "ResultOf<typeof operation> (full fields: Ops/Rows below)".into()
            };
            let session = if session.len() <= 250 {
                session
            } else {
                format!(
                    "caller guards at {}; use the required account/service credential",
                    p.site
                )
            };
            let codes = if codes.len() <= 160 {
                codes
            } else {
                format!(
                    "{} codes: see this operation's Require codes in Ops below",
                    fact.requires.len()
                )
            };
            out.push_str(&format!("\n## {} {}\n\nArgs: `{args}`. Result: `{result}`.\nSession: {session}.\nDeclared refusals: {codes}.{note}\n\n",kind.word(),p.program.name));
        } else {
            out.push_str(&header);
        }
        out.push_str(&calls);
    }
    out
}

pub(super) fn emit(bound: &Bound, spanning: bool, out: &mut String) {
    out.push_str(START);
    // An authored text literal must never terminate this comment or inject code.
    out.push_str(&markdown(bound, spanning).replace("*/", "*\\/"));
    out.push_str(END);
    out.push_str("\n\n");
}
fn compact_args(text: &str) -> String {
    text.replace(&ty_ts(&Ty::Image), "{ id: string }")
        .replace(&ty_ts(&Ty::File), "{ id: string }")
}
fn compact_ty(ty: &Ty) -> String {
    compact_args(&ty_ts(ty))
}
fn result_rows(ty: &Ty, rows: &mut BTreeSet<String>) {
    match ty {
        Ty::Row(t) | Ty::WriteRow(t) | Ty::Page(t, _) => {
            rows.insert(t.clone());
        }
        Ty::List(t, _) | Ty::Collection(t, _) | Ty::Optional(t) | Ty::Omittable(t) => {
            result_rows(t, rows)
        }
        Ty::Object(fields) | Ty::RowShape(fields) | Ty::RowObject(fields) => {
            for t in fields.values() {
                result_rows(t, rows);
            }
        }
        _ => {}
    }
}

// Actions have a small, closed admission grammar and no authored $clause map.
// Render that IR exactly; do not infer row authorization or an allowed-role set.
fn action_rule(expr: &Expr) -> Option<String> {
    Some(match expr {
        Expr::Literal(snapback4_core::Value::Bool(value)) => {
            if *value { "allow" } else { "deny" }.into()
        }
        Expr::Literal(snapback4_core::Value::Id(value) | snapback4_core::Value::String(value)) => {
            string_literal(value)
        }
        Expr::Input(Input::Viewer) => "viewer".into(),
        Expr::Unary {
            op: UnaryOp::Not,
            value,
        } => format!("not ({})", action_rule(value)?),
        Expr::Binary { op, left, right } => {
            let word = match op {
                BinaryOp::Eq => "=",
                BinaryOp::Ne => "!=",
                BinaryOp::And => "and",
                BinaryOp::Or => "or",
                _ => return None,
            };
            format!("({} {word} {})", action_rule(left)?, action_rule(right)?)
        }
        _ => return None,
    })
}
