//! Handler signatures and the declaration manifest, built beside api.ts.
use super::{args_ts, property, string_literal, ty_ts};
use crate::bind::Bound;
use snapback4_core::ir::ProgramKind;

// @ref LLP 3000.009#5.1 — client and handler types come from one declaration; the contract binds the worker to it.
pub fn server_typescript(bound: &Bound) -> String {
    let mut out = String::from("// Generated by snapback4 from snapback/*.q. Do not edit; edit the schema.\nimport { startServer, type ServerContext, type ServerOptions, type RouteHandler, type ServiceRoute } from \"snapback4/server\";\nimport type { Cursor } from \"snapback4/contract\";\nimport type { EffectHandler } from \"snapback4/worker\";\n\n");
    let actions = bound.programs.iter().filter(|p| p.program.kind == ProgramKind::Action).collect::<Vec<_>>();
    out.push_str(if actions.is_empty() { "export type Actions = Record<string, never>;\n" } else { "export type Actions = {\n" });
    for action in &actions {
        let spec = &bound.schema.action_specs[&action.program.name];
        let secrets = union(&spec.work.secrets);
        let result = ty_ts(&action.result);
        out.push_str(&format!("  {}: (args: {}, ctx: ServerContext<{secrets}>) => Promise<{result}> | {result};\n", property(&action.program.name), args_ts(&action.args)));
    }
    if !actions.is_empty() { out.push_str("};\n"); }
    let routes = &bound.schema.routes;
    out.push_str(if routes.is_empty() { "\nexport type Routes = Record<string, never>;\n" } else { "\nexport type Routes = {\n" });
    for (name, spec) in routes {
        let handler = if spec.service.is_some() { "ServiceRoute" } else { "RouteHandler" };
        out.push_str(&format!("  {}: {handler}<{}>;\n", property(name), union(&spec.work.secrets)));
    }
    if !routes.is_empty() { out.push_str("};\n"); }
    out.push_str("\nexport const manifest = {\n  actions: {\n");
    for action in &actions {
        let spec = &bound.schema.action_specs[&action.program.name];
        let secrets = spec.work.secrets.iter().map(|s| string_literal(s)).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("    {}: {{ contract: {}, secrets: [{secrets}] }},\n", property(&action.program.name), string_literal(&spec.contract(&action.program))));
    }
    out.push_str("  },\n  routes: {\n");
    for (name, spec) in routes {
        let secrets = spec.work.secrets.iter().map(|s| string_literal(s)).collect::<Vec<_>>().join(", ");
        let service = spec.service.as_ref().map_or_else(|| "null".into(), |s| string_literal(s));
        out.push_str(&format!("    {}: {{ contract: {}, method: \"POST\", path: {}, service: {service}, secrets: [{secrets}] }},\n", property(name), string_literal(&spec.contract(name)), string_literal(&spec.path)));
    }
    out.push_str("  },\n  effects: {\n");
    for (name, spec) in &bound.schema.effect_specs {
        let secrets = spec.secrets.iter().map(|s| string_literal(s)).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("    {}: {{ secrets: [{secrets}] }},\n", property(name)));
    }
    out.push_str("  },\n} as const;\n\n");
    let effects = if bound.schema.effects.is_empty() { "Record<string, never>".into() } else { format!("Partial<Record<{}, EffectHandler>>", union(&bound.schema.effects)) };
    let actions_optional = if actions.is_empty() { "?" } else { "" };
    let routes_optional = if routes.is_empty() { "?" } else { "" };
    out.push_str(&format!("export function server(handlers: {{ actions{actions_optional}: Actions; routes{routes_optional}: Routes; effects?: {effects} }}, options?: ServerOptions) {{\n  return startServer(manifest, handlers, options);\n}}\n"));
    out
}

fn union(names: &[String]) -> String {
    if names.is_empty() { "never".into() } else { names.iter().map(|s| string_literal(s)).collect::<Vec<_>>().join(" | ") }
}
