//! The client's types, by inference: one generated TypeScript module with
//! the row types, every operation's argument and result types, and the
//! `api` object the app imports. Built, never committed.

pub mod rust;
pub use rust::rust;
mod server;
pub use server::server_typescript;

use crate::bind::{Bound, BoundProgram};
use crate::types::Ty;
use snapback4_core::ir::ProgramKind;
use snapback4_core::schema::{ColumnType, Schema};
use std::collections::BTreeMap;

pub fn typescript(bound: &Bound) -> String {
    let mut out = String::new();
    out.push_str("// Generated by snapback4 from snapback/*.q. Do not edit; edit the schema.\n");
    let action = if bound.server { "Action, " } else { "" };
    out.push_str(&format!("import type {{ {action}Cursor, Mutation, Query }} from \"snapback4/contract\";\n\n"));
    out.push_str("export type Rows = {\n");
    for (name, table) in bound.schema.visible_tables() {
        out.push_str(&format!("  {}: {{\n", property(name)));
        for (column, kind) in table.columns.iter().filter(|(name, _)| !table.recorded.contains_key(*name)) {
            out.push_str(&format!("    {}: {};\n", property(column), column_ts(kind, &bound.schema)));
        }
        out.push_str("    /** True on this device's own unconfirmed change (the card). */\n    pending?: boolean;\n");
        out.push_str("  };\n");
    }
    let views = &bound.view_types;
    for (name, ty) in views { out.push_str(&format!("  {}: {};\n", property(name), ty_ts(ty))); }
    out.push_str("};\n\n");
    if bound.schema.visible_tables().any(|(_,table)| !table.maintained.is_empty()) {
        out.push_str("export type WriteRows = {\n");
        for (name,table) in bound.schema.visible_tables() {
            let keys = table.maintained.keys().map(|key|string_literal(key)).collect::<Vec<_>>().join(" | ");
            out.push_str(&format!("  {}: Omit<Rows[{}], {}>;\n",property(name),string_literal(name),if keys.is_empty() { "never" } else { &keys }));
        }
        out.push_str("};\n\n");
    }
    let mut modules: BTreeMap<String, Vec<&BoundProgram>> = BTreeMap::new();
    for program in &bound.programs {
        if program.program.kind != ProgramKind::Job {
            modules.entry(program.module.clone()).or_default().push(program);
        }
    }
    out.push_str("export type Ops = {\n");
    for (module, programs) in &modules {
        let indent = if module == "schema" { "  " } else { "    " };
        if module != "schema" {
            out.push_str(&format!("  {}: {{\n", property(module)));
        }
        for program in programs {
            let short = program.program.name.rsplit('.').next().unwrap_or(&program.program.name);
            let kind = match program.program.kind {
                ProgramKind::Query => "Query",
                ProgramKind::Mutation => "Mutation",
                ProgramKind::Action => "Action",
                // A job is the server's to run (a schedule, `snapback4 run`); no client calls it.
                ProgramKind::Job => continue,
            };
            let fact = &bound.schema.operations[&program.program.name];
            let horizon = fact.sites.iter().filter(|site| site.class == snapback4_core::schema::SiteClass::Horizon).map(|site| format!("{} by {} ({})", site.table, site.index, site.site)).collect::<Vec<_>>().join(", ");
            let word = fact.runs.as_ref().map(|word| format!("runs: {word}")).or_else(|| fact.predicts.as_ref().map(|word| format!("predicts: {word}"))).unwrap_or_default();
            let mut comment = format!("Arguments: {}. Result: {}. {word}. Horizon sites: {}. Require codes: {}.", args_ts(&program.args), ty_ts(&program.result), if horizon.is_empty() { "none" } else { &horizon }, if fact.requires.is_empty() { "none".into() } else { fact.requires.join(", ") });
            if fact.held { comment.push_str(" Held: device only; server refuses E_QUERY_HELD; no server fallback."); }
            if program.program.kind == ProgramKind::Query { comment.push_str(" Read.cut: meter | words | null, beside complete."); }
            if fact.connected_effects_only { comment.push_str(&format!(" {}.", crate::bind::residency::CONNECTED_EFFECTS)); }
            if program.program.kind == ProgramKind::Mutation { comment.push_str(" Call client.mutate(op, args, { id }) to retry an intent with its original write id; replay returns a receipt without historical results."); }
            out.push_str(&format!("{indent}/** {} */\n", comment.replace("*/", "* /")));
            out.push_str(&format!("{indent}{}: {kind}<{}, {}>;\n", property(short), args_ts(&program.args), ty_ts(&program.result)));
        }
        if module != "schema" {
            out.push_str("  };\n");
        }
    }
    out.push_str("};\n\n");
    out.push_str("export const api: Ops = {\n");
    for (module, programs) in &modules {
        let indent = if module == "schema" { "  " } else { "    " };
        if module != "schema" {
            out.push_str(&format!("  {}: {{\n", property(module)));
        }
        for program in programs {
            let short = program.program.name.rsplit('.').next().unwrap_or(&program.program.name);
            let kind = match program.program.kind {
                ProgramKind::Query => "query",
                ProgramKind::Mutation => "mutation",
                ProgramKind::Action => "action",
                ProgramKind::Job => continue,
            };
            let fact = &bound.schema.operations[&program.program.name];
            let words = fact.runs.as_ref().map(|word| format!(", runs: {}", string_literal(word))).or_else(|| fact.predicts.as_ref().map(|word| format!(", predicts: {}", string_literal(word)))).unwrap_or_default();
            let words = if fact.held { format!("{words}, held: true") } else { words };
            out.push_str(&format!("{indent}{}: {{ kind: \"{kind}\", name: {}{words} }},\n", property(short), string_literal(&program.program.name)));
        }
        if module != "schema" {
            out.push_str("  },\n");
        }
    }
    out.push_str("};\n");
    out
}

fn args_ts(args: &[(String, Ty)]) -> String {
    if args.is_empty() {
        return "Record<string, never>".into();
    }
    let fields: Vec<String> = args.iter().map(|(name, ty)| if ty.is_optional() { format!("{}?: {}", property(name), ty_ts(ty)) } else { format!("{}: {}", property(name), ty_ts(ty)) }).collect();
    format!("{{ {} }}", fields.join("; "))
}

pub fn ty_ts(ty: &Ty) -> String {
    match ty {
        Ty::Unknown | Ty::Json => "unknown".into(),
        Ty::Null => "null".into(),
        Ty::Bool => "boolean".into(),
        Ty::Int | Ty::Time | Ty::Decimal(_) | Ty::Money(..) => "number".into(),
        Ty::Text(_) | Ty::Id | Ty::Principal | Ty::Ref(_) | Ty::Bytes => "string".into(),
        Ty::Image | Ty::Video => "{ id: string; width?: number | null; height?: number | null; bytes?: number; type?: string; duration?: number | null }".into(),
        Ty::Enum(variants) => variants.iter().map(|v| string_literal(v)).collect::<Vec<_>>().join(" | "),
        Ty::Cursor => "Cursor".into(),
        Ty::Optional(inner) => format!("{} | null", ty_ts(inner)),
        Ty::List(item, _) => format!("{}[]", wrap(item)),
        Ty::Row(table) => format!("Rows[{}]", string_literal(table)),
        Ty::WriteRow(table) => format!("WriteRows[{}]", string_literal(table)),
        Ty::Page(table, _) => format!("Rows[{}][]", string_literal(table)),
        Ty::Collection(item, _) => format!("{}[]", wrap(item)),
        Ty::RowShape(fields) => {
            let fields = fields.iter().map(|(name, ty)| format!("{}: {}", property(name), ty_ts(ty))).chain(["pending?: boolean".into()]).collect::<Vec<_>>();
            format!("{{ {} }}", fields.join("; "))
        }
        Ty::Object(fields) => {
            if fields.is_empty() {
                return "Record<string, never>".into();
            }
            format!("{{ {} }}", fields.iter().map(|(name, ty)| format!("{}: {}", property(name), ty_ts(ty))).collect::<Vec<_>>().join("; "))
        }
    }
}

fn wrap(ty: &Ty) -> String {
    let union_at_top = matches!(ty, Ty::Optional(_)) || matches!(ty, Ty::Enum(variants) if variants.len() > 1);
    let text = ty_ts(ty);
    if union_at_top { format!("({text})") } else { text }
}

fn column_ts(kind: &ColumnType, schema: &Schema) -> String {
    let _ = schema;
    ty_ts(&Ty::from_column(kind))
}

fn property(name: &str) -> String {
    // In an object literal, this spelling must create an own property,
    // rather than invoking JavaScript's prototype-setter syntax.
    if name == "__proto__" {
        return format!("[{}]", string_literal(name));
    }
    let plain = name.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$') && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if plain { name.to_owned() } else { string_literal(name) }
}

fn string_literal(value: &str) -> String {
    serde_json::to_string(value).expect("strings always serialize").replace('\u{2028}', "\\u2028").replace('\u{2029}', "\\u2029")
}

/// The wire adds execution words without changing the interpreter's IR.
pub fn backend_programs(bound: &Bound) -> Vec<serde_json::Value> {
    bound.programs.iter().map(|program| {
        let mut value = serde_json::to_value(&program.program).expect("program JSON");
        let facts = serde_json::to_value(&bound.schema.operations[&program.program.name]).expect("execution JSON");
        value.as_object_mut().expect("program object").extend(facts.as_object().expect("execution object").clone());
        value
    }).collect()
}
