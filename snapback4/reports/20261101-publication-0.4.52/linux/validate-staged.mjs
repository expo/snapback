import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {verifyArtifact, validateLinux, clientManifest, manifest} from '/home/ccheever/sb4-pub-0441/snapback4/scripts/publication-artifacts.mjs';
const r='/home/ccheever/sb4-pub-0452-records', w='/home/ccheever/sb4-pub-0441/snapback4';
const stage=process.argv[2];
if (!stage) throw Error('stage directory required');
const q=JSON.parse(readFileSync(join(stage,'resume.json')));
const source=execFileSync('git',['rev-parse','HEAD'],{cwd:w,encoding:'utf8'}).trim();
if(q.source!==source || q.version!=='0.4.52' || q.format!==3 || q.qualification?.suite!=='passed') throw Error('stage source/version/suite mismatch');
const all=[q.client,q.expo,...q.platforms].map(a=>verifyArtifact(a,stage,q.version));
if (JSON.stringify(all.map(a=>a.name))!==JSON.stringify(['snapback4','snapback4-expo','snapback4-darwin-arm64','snapback4-linux-x64'])) throw Error('unexpected artifact set');
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
for(const a of all) manifest(a.tarball,a.name,q.version);
clientManifest(all[0].tarball,q.version);
for(const a of all.slice(0,2)) if(hash(a.tarball)!==hash(join(w,'target/publication/client-0.4.52',a.filename))) throw Error('canonical prepared bytes changed');
const linux=all[3];
if(hash(linux.tarball)!==hash(join(r,'linux-qualification-0.4.52',linux.filename))) throw Error('qualified Linux bytes changed');
const receipt=JSON.parse(readFileSync(join(stage,'linux-receipt.json')));
const sri='sha512-'+createHash('sha512').update(readFileSync(join(stage,'linux-receipt.json'))).digest('base64');
if(sri!==linux.receiptIntegrity) throw Error('receipt integrity mismatch');
validateLinux(receipt,linux.tarball,{...all[0],expoIntegrity:all[1].integrity},source);
const result={at:new Date().toISOString(),source,version:q.version,status:'passed',artifacts:all.map(a=>({name:a.name,filename:a.filename,integrity:a.integrity,sha256:hash(a.tarball),bytes:a.bytes}))};
writeFileSync(join(r,'staged-validation.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
