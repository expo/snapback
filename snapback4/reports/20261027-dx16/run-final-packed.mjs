import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdirSync,readFileSync,writeFileSync,copyFileSync,chmodSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {proveDX16} from '../../scripts/publication-dx16.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..'),out=join(root,'target/dx16-native6'),pkg=join(out,'package'),consumer=join(root,'target/dx16-fresh-packed');
mkdirSync(pkg,{recursive:true});
const binary=join(root,'target/x86_64-unknown-linux-musl/production/snapback4');
for(const file of ['package.json','THIRD-PARTY-NOTICES'])copyFileSync(join(root,'packages/snapback4-linux-x64',file),join(pkg,file));
copyFileSync(binary,join(pkg,'snapback4'));chmodSync(join(pkg,'snapback4'),0o755);
const env={...process.env};delete env.SNAPBACK4_BIN;
const invoke=(command,args,cwd)=>execFileSync(command,args,{cwd,env,encoding:'utf8',timeout:300000,maxBuffer:10*1024*1024});
const [pack]=JSON.parse(invoke('npm',['pack','--ignore-scripts','--json','--pack-destination',out],pkg));
const tar=join(out,pack.filename),client=join(root,'target/dx16-final-packs/snapback4-0.4.44.tgz');
invoke('npm',['install','--no-save','--ignore-scripts','--no-audit','--no-fund',client,tar],consumer);
const sha=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
assert.equal(sha(join(consumer,'node_modules/snapback4-linux-x64/snapback4')),sha(binary));
const guide=invoke(process.execPath,[join(consumer,'node_modules/snapback4/bin/snapback4.js'),'guide','day2','--repeat'],consumer);
assert.ok(Buffer.byteLength(guide)<=8001);assert.ok(guide.includes('Substitute the chosen pair in ALL examples below, including both proof runs'));
const proof=await proveDX16(consumer);assert.equal(proof.unusedSavedVersions,true);
const result={source:invoke('git',['rev-parse','HEAD'],root).trim(),publicationQualified:false,mode:'affected packed DX16 after guide-only correction',binarySha256:sha(binary),clientSha256:sha(client),nativeTarSha256:sha(tar),guideBytes:Buffer.byteLength(guide),...proof};
writeFileSync(join(out,'result.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
