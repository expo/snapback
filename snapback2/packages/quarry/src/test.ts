test("walked rows and shaped page rows stay values rather than references", async () => {
  const schema = `table nodes:\n  parent: nodes?\n  name: text <=50\n  public\n  by name\n\ntable copies:\n  name: text <=50\n  public\n`;
  const module = `mutation copyWalk(seed: nodes):\n  for ancestor in walk nodes[seed] up .parent depth 3:\n    name = ancestor.name\n  null\n\nmutation copyPage():\n  for node in nodes[] first 3 by byName { * }:\n    name = node.name\n  null\n`;
  await withSources(schema, module, async (root) => {
    const result = await compileApp(root);
    assert(result.ok, `walk/page compilation failed: ${result.ok ? "" : JSON.stringify(result.diagnostics)}`);
    const generated = await readFile(join(root, "snapback", "bad.ts"), "utf8");
    assert(!generated.includes("db.get(nodes, ancestor)"), `walked row was dereferenced as a key:\n${generated}`);
    assert(!generated.includes("db.get(nodes, node)"), `shaped page row was dereferenced as a key:\n${generated}`);
    assert(generated.includes("= ancestor.name") && generated.includes("= node?.name"), "row fields were not read from the yielded objects");
    await certify(root);
  });
});

