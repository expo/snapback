const baseSchema = `use identity\n\ntable todos:\n  owner: id\n  public\n`;

async function withSources(schema: string, module: string | undefined, run: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(join(tmpdir(), "quarry-refusal-"));
  try {
    await mkdir(join(root, "snapback-quarry"), { recursive: true });
    await writeFile(join(root, "snapback-quarry", "schema.q"), schema);
    if (module !== undefined) await writeFile(join(root, "snapback-quarry", "bad.q"), module);
    await run(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

async function command(executable: string, args: string[], cwd: string, env = process.env): Promise<string> {
  const child = Bun.spawn([executable, ...args], { cwd, env, stdout: "pipe", stderr: "pipe" });
  const [stdout, stderr, exit] = await Promise.all([new Response(child.stdout).text(), new Response(child.stderr).text(), child.exited]);
  if (exit !== 0) throw new Error(`${executable} ${args.join(" ")} exited ${exit}\n${stdout}\n${stderr}`);
  return `${stdout}\n${stderr}`.trim();
}

function greenLine(output: string): string {
  return output.split("\n").map((line) => line.trim()).filter(Boolean).at(-1) ?? "ok";
}

let failures = 0;
for (const check of checks) {
  try {
    await check.run();
    console.log(`ok quarry: ${check.name}`);
  } catch (error) {
    failures += 1;
    console.error(`not ok quarry: ${check.name}\n${error instanceof Error ? error.stack : String(error)}`);
  }
}
if (failures > 0) process.exitCode = 1;
