function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message);
}

async function scratchFixture(name: string, run: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(join(tmpdir(), `quarry-${name}-`));
  try {
    await cp(join(here, "fixtures", name), root, { recursive: true });
    await removeGenerated(root);
    await run(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

async function removeGenerated(root: string): Promise<void> {
  for (const name of ["schema.ts", "schema.q.ts", "todos.ts", "todos.q.ts", "surface.ts", "surface.q.ts"]) {
    await rm(join(root, "snapback", name), { force: true });
  }
}

async function certify(root: string): Promise<{ programs: number }> {
  const lowered = await lowerProject(root);
  assert(lowered.ok, `packaged compiler refused: ${lowered.ok ? "" : lowered.diagnostics.map((item) => `${item.site} ${item.message}`).join("; ")}`);
  const checked = rustCheck(lowered.project.programs, "synthetic", lowered.project.schema);
  const errors = checked.filter((item) => item.error);
  assert(errors.length === 0, `engine certification refused: ${JSON.stringify(errors)}`);
  return { programs: lowered.project.programs.length };
}

test("todos Quarry fixture emits sited TypeScript and certifies", async () => {
  await scratchFixture("todos-quarry", async (root) => {
    const compiled = await compileApp(root);
    assert(compiled.ok, `quarryc refused todos: ${compiled.ok ? "" : JSON.stringify(compiled.diagnostics)}`);
    const generated = await readFile(join(root, "snapback", "todos.q.ts"), "utf8");
    assert(generated.startsWith("// GENERATED by quarryc from snapback-quarry/todos.q — do not edit"), "generated header missing");
    assert(generated.includes("// q:todos.q:2") && generated.includes("db.scan(todos.byOwner"), "statement provenance or scan lowering missing");
    const certified = await certify(root);
    assert(certified.programs === 5, `todos bridge program count changed: ${certified.programs}`);
  });
});

test("full fixture covers supported constructs and certifies", async () => {
  await scratchFixture("full-surface", async (root) => {
    const compiled = await compileApp(root);
    assert(compiled.ok, `quarryc refused full surface: ${compiled.ok ? "" : JSON.stringify(compiled.diagnostics)}`);
    const schema = await readFile(join(root, "snapback", "schema.ts"), "utf8");
    const programs = await readFile(join(root, "snapback", "surface.ts"), "utf8");
    for (const spelling of ["rule.and(", "rule.or(", "rule.not(", "rule.exists(", "channel({", "t.optional(", "t.enum("]) {
      assert(schema.includes(spelling), `schema lowering lost ${spelling}`);
    }
    for (const spelling of ["db.upsert(", "orderedPair(", "mentionTokens(", "recurse(", "order: \"desc\"", "after: args.cursor", "let __q_matchResult", "db.get(users"]) {
      assert(programs.includes(spelling), `program lowering lost ${spelling}`);
    }
    const certified = await certify(root);
    assert(certified.programs === 33, `full bridge program count changed: ${certified.programs}`);
  });
});

test("out-of-subset constructs have one clear sited refusal", async () => {
  const cases: Array<{ name: string; schema: string; module?: string; needle: string; site: string }> = [
    { name: "maintain", schema: "maintain n = count todos by owner\n", needle: "maintain declarations", site: "schema.q:1:1" },
    { name: "aggregate", schema: baseSchema, module: "query bad():\n  #n[viewer]\n", needle: "#agg", site: "bad.q:2:3" },
    { name: "rule-chain", schema: `table users:\n  name: text <=20\n  public\n\ntable journals:\n  owner: users\n  read r <- journals[r.owner].owner = viewer\n`, needle: "point-read field chains", site: "schema.q:7:30" },
    { name: "while", schema: baseSchema, module: "query bad():\n  while true:\n    todos[viewer]\n", needle: "while is not part of Quarry", site: "bad.q:2:3" },
  ];
  for (const item of cases) {
    await withSources(item.schema, item.module, async (root) => {
      const result = await compileApp(root);
      assert(!result.ok && result.diagnostics.length === 1, `${item.name}: expected one refusal, got ${JSON.stringify(result)}`);
      const diagnostic = result.diagnostics[0]!;
      assert(`${diagnostic.file}:${diagnostic.line}:${diagnostic.col}` === item.site, `${item.name}: site changed to ${diagnostic.file}:${diagnostic.line}:${diagnostic.col}`);
      assert(diagnostic.message.includes(item.needle), `${item.name}: message changed to ${diagnostic.message}`);
    });
  }
});

test("hand-written TypeScript collisions are preserved", async () => {
  await withSources(baseSchema, "query list():\n  todos[viewer]\n", async (root) => {
    await mkdir(join(root, "snapback"), { recursive: true });
    await writeFile(join(root, "snapback", "bad.ts"), "// hand written\n");
    const result = await compileApp(root);
    assert(!result.ok && result.diagnostics[0]?.message.includes("refusing to overwrite hand-written"), "hand-written collision was not refused");
    assert(await readFile(join(root, "snapback", "bad.ts"), "utf8") === "// hand written\n", "hand-written collision was modified");
  });
});

