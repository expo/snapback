#!/usr/bin/env node
// Generate the pinned Unicode 17 tables used by portable full-text search.
// Network input is versioned and HTTPS-pinned; the build consumes only the
// committed Rust output.

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const version = '17.0.0';
const base = `https://www.unicode.org/Public/${version}/ucd`;
const urls = {
  derivedCore: `${base}/DerivedCoreProperties.txt`,
  derivedNormalization: `${base}/DerivedNormalizationProps.txt`,
  generalCategory: `${base}/extracted/DerivedGeneralCategory.txt`,
};

const sources = {};
for (const [name, url] of Object.entries(urls)) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`failed to fetch ${url}: ${response.status}`);
  sources[name] = await response.text();
}

const parseRange = (source) => {
  const [start, end = start] = source.split('..');
  return [Number.parseInt(start, 16), Number.parseInt(end, 16)];
};

const propertyRanges = (source, wanted) => {
  const ranges = [];
  for (const line of source.split(/\r?\n/u)) {
    const body = line.split('#')[0].trim();
    if (!body) continue;
    const [range, property] = body.split(';').map((part) => part.trim());
    if (wanted(property)) ranges.push(parseRange(range));
  }
  return ranges;
};

const sortAndMergeRanges = (ranges) => {
  const sorted = ranges.toSorted(([left], [right]) => left - right);
  const merged = [];
  for (const [start, end] of sorted) {
    const prior = merged.at(-1);
    if (prior && start <= prior[1] + 1) {
      prior[1] = Math.max(prior[1], end);
    } else {
      merged.push([start, end]);
    }
  }
  return merged;
};

const defaultIgnorable = sortAndMergeRanges(propertyRanges(
  sources.derivedCore,
  (property) => property === 'Default_Ignorable_Code_Point',
));
const lettersNumbers = sortAndMergeRanges(propertyRanges(
  sources.generalCategory,
  (property) => property.startsWith('L') || property.startsWith('N'),
));
const marks = sortAndMergeRanges(propertyRanges(
  sources.generalCategory,
  (property) => property.startsWith('M'),
));
const controls = sortAndMergeRanges(propertyRanges(
  sources.generalCategory,
  (property) => property === 'Cc',
));

const nfkcCaseFold = [];
for (const line of sources.derivedNormalization.split(/\r?\n/u)) {
  const body = line.split('#')[0].trim();
  if (!body) continue;
  const [source, property, mapping = ''] = body.split(';').map((part) => part.trim());
  if (property !== 'NFKC_CF') continue;
  const [start, end] = parseRange(source);
  const scalars = mapping
    ? mapping.split(/\s+/u).map((value) => Number.parseInt(value, 16))
    : [];
  for (let scalar = start; scalar <= end; scalar += 1) {
    nfkcCaseFold.push([scalar, scalars]);
  }
}
nfkcCaseFold.sort(([left], [right]) => left - right);

const digest = createHash('sha256');
for (const name of Object.keys(urls).sort()) {
  digest.update(`${name}\0${urls[name]}\0`, 'utf8');
  digest.update(sources[name], 'utf8');
}
digest.update('snapback-category-unicode17-v1.generator-v3.normative-nfkc-cf\0', 'utf8');

const hex = (value) => `0x${value.toString(16).toUpperCase()}`;
const renderRanges = (name, ranges) => [
  `const ${name}: &[(u32, u32)] = &[`,
  ...ranges.map(([start, end]) => `    (${hex(start)}, ${hex(end)}),`),
  '];',
].join('\n');

const rendered = `//! Generated by scripts/generate-search-unicode.mjs. Do not edit.
//!
//! @ref LLP 0073#canonical-text-and-analyzer — Unicode category, default-
//! ignorable, and full case-fold behavior is pinned to Unicode ${version}.

pub const UNICODE_VERSION: &str = "${version}";
pub const ANALYZER_ID: &str = "snapback-category-unicode17-v1";
pub const ANALYZER_TABLES_DIGEST: &str =
    "sha256:${digest.digest('hex')}";

fn range_contains(ranges: &[(u32, u32)], value: u32) -> bool {
    ranges
        .binary_search_by(|(start, end)| {
            if value < *start {
                std::cmp::Ordering::Greater
            } else if value > *end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

${renderRanges('DEFAULT_IGNORABLE', defaultIgnorable)}

${renderRanges('LETTERS_NUMBERS', lettersNumbers)}

${renderRanges('MARKS', marks)}

${renderRanges('CONTROLS', controls)}

const NFKC_CASE_FOLD: &[(u32, &[u32])] = &[
${nfkcCaseFold.map(([source, mapping]) => `    (${hex(source)}, &[${mapping.map(hex).join(', ')}]),`).join('\n')}
];

pub fn is_default_ignorable(ch: char) -> bool {
    range_contains(DEFAULT_IGNORABLE, ch as u32)
}

pub fn is_control(ch: char) -> bool {
    range_contains(CONTROLS, ch as u32)
}

pub fn is_mark(ch: char) -> bool {
    range_contains(MARKS, ch as u32)
}

pub fn is_letter_or_number(ch: char) -> bool {
    range_contains(LETTERS_NUMBERS, ch as u32)
}

pub fn nfkc_case_fold(ch: char, mut emit: impl FnMut(char)) {
    match NFKC_CASE_FOLD.binary_search_by_key(&(ch as u32), |(source, _)| *source) {
        Ok(index) => {
            for scalar in NFKC_CASE_FOLD[index].1 {
                if let Some(output) = char::from_u32(*scalar) {
                    emit(output);
                }
            }
        }
        Err(_) => emit(ch),
    }
}
`;

const output = resolve(import.meta.dirname, '..', 'crates', 'snapback', 'src', 'search', 'unicode17_generated.rs');
writeFileSync(output, rendered);
process.stdout.write(`wrote ${output}\n`);
