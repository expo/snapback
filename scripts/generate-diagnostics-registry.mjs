function lineAndColumn(source, offset) {
  const before = source.slice(0, offset);
  const line = before.split('\n').length;
  const lastNewline = before.lastIndexOf('\n');
  return { line, column: offset - lastNewline };
}

function subsystemFor(code, sites) {
  const family = code.slice('SNAPBACK_'.length).split('_')[0];
  const families = {
    APP: 'application',
    ASSET: 'assets',
    AUTH: 'auth',
    AUTHORING: 'codegen',
    CAPABILITY: 'capabilities',
    CLIENT: 'client',
    CODEGEN: 'codegen',
    CONNECTION: 'realtime',
    CONTRACT: 'contract',
    EXTERNAL: 'client',
    GUIDE: 'guide',
    IBEX: 'runtime',
    LIVE: 'realtime',
    MCP: 'mcp',
    MIGRATION: 'migrations',
    OPTIMISTIC: 'client',
    QUERY: 'queries',
    RUNTIME: 'runtime',
    SEED: 'seeds',
    STORE: 'storage',
    SWIFT: 'swift-client',
    TELEMETRY: 'telemetry',
  };
  if (families[family]) return families[family];
  // Preserve the pre-workspace semantic precedence explicitly. Rust files
  // may move through several workspace crates during LLP 0276; repository
  // path ordering must never reclassify a published diagnostic.
  const sitePriority = (file) => {
    if (file.startsWith('clients/swift/')) return 0;
    if (file.startsWith('packages/')) return 1;
    if (file.startsWith('src/') || file.startsWith('crates/')) return 2; // path-migration: historical
    return 3;
  };
  const first = [...sites].sort((left, right) => (
    sitePriority(left.file) - sitePriority(right.file)
      || left.file.localeCompare(right.file)
      || left.line - right.line
      || left.column - right.column
  ))[0]?.file ?? '';
  const packageMatch = first.match(/^packages\/([^/]+)/u);
  if (packageMatch) return packageMatch[1].replace(/^snapback-/u, '');
  if (first.startsWith('clients/swift/')) return 'swift-client';
  return first.startsWith('src/') || first.startsWith('crates/') ? 'server' : 'snapback'; // path-migration: historical
}

function assertPathRelocationPreservesSubsystem(code, sites) {
  const legacySites = sites.map((site) => ({
    ...site,
    file: site.file.replace(/^crates\/[^/]+\/src\//u, 'src/'), // path-migration: historical
  }));
  const current = subsystemFor(code, sites);
  const legacy = subsystemFor(code, legacySites);
  if (current !== legacy) {
    throw new Error(
      `[diagnostics-registry] path-only relocation reclassified ${code}: ${legacy} -> ${current}`,
    );
  }
}

function collectSites() {
  const sources = new Map(productionPaths.map((path) => (
    [path, readFileSync(join(root, path), 'utf8')]
  )));
  const environmentNames = new Set();
  for (const [path, source] of sources) {
    for (const { match } of environmentVariableSites(source, {
      javascript: /\.(?:cjs|js|mjs)$/u.test(path),
      ordinaryMultiline: path.endsWith('.rs'),
    })) {
      environmentNames.add(match[0]);
    }
  }

  const byCode = new Map();
  const byEnvironmentVariable = new Map();
  for (const path of productionPaths) {
    const source = sources.get(path);
    const sourceOptions = {
      environmentNames,
      javascript: /\.(?:cjs|js|mjs)$/u.test(path),
      ordinaryMultiline: path.endsWith('.rs'),
      // These are public client arms selected from their shipped package
      // manifests above. A closed literal table must also feed a dispatch
      // membership test; all other catalogues remain reference-only.
      receivedProtocolVocabulary: shippedClientProtocolRoots.some((rootPath) => (
        path.startsWith(rootPath)
      )),
    };
    for (const { match, kind, synthetic } of diagnosticSourceSites(source, sourceOptions)) {
      const code = match[0];
      const location = lineAndColumn(source, match.index);
      const sites = byCode.get(code) ?? [];
      sites.push({
        file: path,
        ...location,
        ...(kind === 'emission' ? {} : { kind }),
        ...(synthetic === true ? { synthetic: true } : {}),
      });
      byCode.set(code, sites);
    }
    for (const { match, kind } of environmentVariableSites(source, sourceOptions)) {
      const name = match[0];
      const location = lineAndColumn(source, match.index);
      const sites = byEnvironmentVariable.get(name) ?? [];
      sites.push({ file: path, ...location, kind });
      byEnvironmentVariable.set(name, sites);
    }
  }
  return { byCode, byEnvironmentVariable };
}

const HTTP_STATUS_NUMBERS = {
  BAD_GATEWAY: 502,
  BAD_REQUEST: 400,
  CONFLICT: 409,
  FORBIDDEN: 403,
  GATEWAY_TIMEOUT: 504,
  GONE: 410,
  INTERNAL_SERVER_ERROR: 500,
  MISDIRECTED_REQUEST: 421,
  NOT_FOUND: 404,
  NOT_IMPLEMENTED: 501,
  PAYLOAD_TOO_LARGE: 413,
  PRECONDITION_FAILED: 412,
  REQUEST_TIMEOUT: 408,
  SERVICE_UNAVAILABLE: 503,
  TOO_MANY_REQUESTS: 429,
  UNAUTHORIZED: 401,
  UNPROCESSABLE_ENTITY: 422,
  UNSUPPORTED_MEDIA_TYPE: 415,
};

function parseHttpStatuses() {
  // @ref LLP 0199#sequencing-guidance-not-a-schedule — the reviewed family
  // table moved with the server's extracted test owner.
  const source = readFileSync(join(root, 'crates/snapback-server/src/server/tests.rs'), 'utf8');
  const families = new Map();
  for (const match of source.matchAll(/const\s+([A-Z0-9_]+):\s*&\[&str\]\s*=\s*&\[(.*?)\];/gsu)) {
    families.set(match[1], [...match[2].matchAll(/"(SNAPBACK_[A-Z0-9_]+)"/gu)].map((item) => item[1]));
  }
  const statuses = new Map();
  // StatusCode/family tuples occur only in the reviewed HTTP status table;
  // matching the tuples themselves avoids depending on rustfmt's wrapping of
  // the table's nested slice type.
  for (const match of source.matchAll(/\(\s*StatusCode::([A-Z_]+)\s*,\s*([A-Z0-9_]+)\s*,?\s*\)/gu)) {
    const status = HTTP_STATUS_NUMBERS[match[1]];
    if (!status) continue;
    for (const code of families.get(match[2]) ?? []) statuses.set(code, status);
  }
  for (const match of source.matchAll(/\(\s*(\d{3})\s*,\s*&\[\s*"(SNAPBACK_[A-Z0-9_]+)"\s*\]\s*,?\s*\)/gu)) {
    statuses.set(match[2], Number(match[1]));
  }
  return statuses;
}

function headingSlug(text) {
  const plain = text
    .replace(/`([^`]*)`/gu, '$1')
    .replace(/!\[([^\]]*)\]\([^)]*\)/gu, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/gu, '$1')
    .replace(/[*_~]/gu, '')
    .trim();
  return plain
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s+/gu, '-') || 'section';
}

function guideAnchors(knownCodes) {
  const anchors = new Map();
  const headingAnchors = new Map();
  const explicitPrimaryAnchors = new Map();
  const explicitPrimaryLocations = new Map();
  // Retrieval-eval is the routing-test corpus, not an author-facing diagnostic
  // target; its seeded codes must not capture or demote their tested anchors.
  // @ref LLP 0223#tickets — eval-run transcripts are retained evidence of the
  // retrieval protocol, not retrieval targets, so transcript vocabulary is
  // excluded from anchoring too.
  const guideRoot = guideFixtureRoot === null
    ? join(root, 'guide')
    : resolve(root, guideFixtureRoot);
  const guideRootRelative = relative(root, guideRoot).replaceAll('\\', '/');
  if (guideRootRelative === '..' || guideRootRelative.startsWith('../')) {
    throw new Error(
      '[diagnostics-registry] SNAPBACK_DIAGNOSTIC_FIXTURE_INVALID: '
        + '--guide-fixture-root must stay inside the repository',
    );
  }
  const paths = walk(guideRoot, (path) => (
    path.endsWith('.md')
    && !/^guide\/guide-flat(?:\.[a-z0-9-]+)?\.generated\.md$/.test(path)
    && !path.startsWith('guide/reference/')
    && path !== 'guide/retrieval-eval.md'
    && !path.startsWith('guide/eval-runs/')
  ));
  for (const path of paths) {
    const source = readFileSync(join(root, path), 'utf8');
    const lines = source.split('\n');
    const seenSlugs = new Map();
    let anchor = null;
    let inFence = false;
    for (const line of lines) {
      if (/^```/u.test(line)) inFence = !inFence;
      const heading = inFence ? null : line.match(/^#{1,6}\s+(.+)$/u);
      if (heading) {
        const base = headingSlug(heading[1]);
        const count = seenSlugs.get(base) ?? 0;
        seenSlugs.set(base, count + 1);
        anchor = count === 0 ? base : `${base}-${count}`;
      }
      const explicitPrimary = inFence
        ? null
        : line.match(/^<!-- diagnostic-primary: (SNAPBACK_[A-Z0-9_]+) -->$/u);
      if (explicitPrimary) {
        const code = explicitPrimary[1];
        if (!anchor) {
          throw new Error(`${path}: diagnostic-primary must follow a heading`);
        }
        if (!knownCodes.has(code)) {
          throw new Error(
            `[diagnostics-registry] SNAPBACK_DIAGNOSTIC_PRIMARY_UNKNOWN_CODE: ${path}`
              + ` diagnostic-primary names unknown diagnostic ${code}`,
          );
        }
        const firstLocation = explicitPrimaryLocations.get(code);
        if (firstLocation) {
          throw new Error(
            `[diagnostics-registry] SNAPBACK_DIAGNOSTIC_PRIMARY_MULTIPLE: ${path}#${anchor}`
              + ` is a second diagnostic-primary for ${code}; first marker is at ${firstLocation}`,
          );
        }
        const value = `/_snapback/${path}#${anchor}`;
        explicitPrimaryLocations.set(code, `${path}#${anchor}`);
        const values = anchors.get(code) ?? new Set();
        values.add(value);
        anchors.set(code, values);
        const preferred = explicitPrimaryAnchors.get(code) ?? new Set();
        preferred.add(value);
        explicitPrimaryAnchors.set(code, preferred);
        continue;
      }
      for (const match of line.matchAll(CODE_PATTERN)) {
        if (!anchor) continue;
        const values = anchors.get(match[0]) ?? new Set();
        const value = `/_snapback/${path}${anchor ? `#${anchor}` : ''}`;
        values.add(value);
        anchors.set(match[0], values);
        if (heading?.[1].includes(match[0])) {
          const preferred = headingAnchors.get(match[0]) ?? new Set();
          preferred.add(value);
          headingAnchors.set(match[0], preferred);
        }
      }
    }
  }
  return new Map([...anchors].map(([code, values]) => {
    const explicit = [...(explicitPrimaryAnchors.get(code) ?? [])].sort();
    const heading = [...(headingAnchors.get(code) ?? [])]
      .filter((value) => !explicit.includes(value))
      .sort();
    const remaining = [...values]
      .filter((value) => !explicit.includes(value) && !heading.includes(value))
      .sort();
    return [code, [...explicit, ...heading, ...remaining]];
  }));
}

function sourceDigest(paths) {
  const hash = createHash('sha256');
  for (const path of paths) {
    hash.update(path).update('\0').update(readFileSync(join(root, path))).update('\0');
  }
  return `sha256:${hash.digest('hex')}`;
}

function escapeTable(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

