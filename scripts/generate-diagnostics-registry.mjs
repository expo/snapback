#!/usr/bin/env node
// Generate the build-bound diagnostics vocabulary, its Guide projection, and
// the public TypeScript code union. Output is sorted and carries no wall-clock
// value, so identical inputs always produce identical bytes.
// @ref LLP 0193#program — D1's complete source inventory is the substrate for
// exact error lookup and typed client diagnostics.

import { createHash } from 'node:crypto';
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { authoritiesDigest } from './guide-lib.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const CODE_PATTERN = /SNAPBACK_[A-Z0-9_]+/gu;
const generatedMarker = '<!-- Generated by scripts/generate-diagnostics-registry.mjs. Never hand-edit. -->';
const outputs = {
  registry: 'guide/reference/diagnostics-registry.json',
  markdown: 'guide/reference/diagnostics.md',
  types: 'packages/snapback-client/diagnostic-codes.d.mts',
};
const markdownAuthorities = [
  'llp/0193-errors-as-docs-completeness.plan.md',
  'scripts/generate-diagnostics-registry.mjs',
  'crates/snapback/src/server/api_error.rs',
  'crates/snapback/src/server/tests.rs',
];

function walk(directory, accept) {
  const paths = [];
  if (!existsSync(directory)) return paths;
  for (const entry of readdirSync(directory).sort()) {
    const absolute = join(directory, entry);
    const repoPath = relative(root, absolute).replaceAll('\\', '/');
    if (statSync(absolute).isDirectory()) {
      if (!/(^|\/)(node_modules|tests?|fixtures?|templates?)(\/|$)/u.test(repoPath)) {
        paths.push(...walk(absolute, accept));
      }
    } else if (accept(repoPath)) {
      paths.push(repoPath);
    }
  }
  return paths;
}

const diagnosticCatalogPaths = [
  // This executable table projects diagnostic metadata into the generated
  // handler profile, but it does not emit the diagnostics itself. Keep it in
  // the registry input digest below without treating catalog entries as sites.
  'packages/snapback-codegen/handler-runtime-profile.mjs',
];

const productionPaths = [
  // @ref LLP 0199#sequencing-guidance-not-a-schedule — these files inherit
  // `#[cfg(test)]` from their parent modules; a filesystem walk does not.
  ...walk(join(root, 'crates/snapback/src'), (path) => path.endsWith('.rs')
    && !/^crates\/snapback\/src\/(?:cli|local|server|storage)\/tests\.rs$/u.test(path)),
  ...walk(join(root, 'packages'), (path) => (
    path.endsWith('.mjs')
    && !/(?:^|\.)test\.mjs$/u.test(path)
    && !/(?:^|\.)fixture\.mjs$/u.test(path)
    && !diagnosticCatalogPaths.includes(path)
  )),
  ...walk(join(root, 'clients/swift'), (path) => path.endsWith('.swift') && path.includes('/Sources/')),
].sort();

function lineAndColumn(source, offset) {
  const before = source.slice(0, offset);
  const line = before.split('\n').length;
  const lastNewline = before.lastIndexOf('\n');
  return { line, column: offset - lastNewline };
}

function subsystemFor(code, sites) {
  const family = code.slice('SNAPBACK_'.length).split('_')[0];
  const families = {
    APP: 'application',
    ASSET: 'assets',
    AUTH: 'auth',
    AUTHORING: 'codegen',
    CAPABILITY: 'capabilities',
    CLIENT: 'client',
    CODEGEN: 'codegen',
    CONNECTION: 'realtime',
    CONTRACT: 'contract',
    EXTERNAL: 'client',
    GUIDE: 'guide',
    IBEX: 'runtime',
    LIVE: 'realtime',
    MCP: 'mcp',
    MIGRATION: 'migrations',
    OPTIMISTIC: 'client',
    QUERY: 'queries',
    RUNTIME: 'runtime',
    SEED: 'seeds',
    STORE: 'storage',
    SWIFT: 'swift-client',
    TELEMETRY: 'telemetry',
  };
  if (families[family]) return families[family];
  const first = sites[0]?.file ?? '';
  const packageMatch = first.match(/^packages\/([^/]+)/u);
  if (packageMatch) return packageMatch[1].replace(/^snapback-/u, '');
  if (first.startsWith('clients/swift/')) return 'swift-client';
  return first.startsWith('crates/snapback/src/') ? 'server' : 'snapback';
}

function collectSites() {
  const byCode = new Map();
  for (const path of productionPaths) {
    const source = readFileSync(join(root, path), 'utf8');
    for (const match of source.matchAll(CODE_PATTERN)) {
      const code = match[0];
      const location = lineAndColumn(source, match.index);
      const sites = byCode.get(code) ?? [];
      sites.push({ file: path, ...location });
      byCode.set(code, sites);
    }
  }
  return byCode;
}

const HTTP_STATUS_NUMBERS = {
  BAD_GATEWAY: 502,
  BAD_REQUEST: 400,
  CONFLICT: 409,
  FORBIDDEN: 403,
  GATEWAY_TIMEOUT: 504,
  GONE: 410,
  INTERNAL_SERVER_ERROR: 500,
  MISDIRECTED_REQUEST: 421,
  NOT_FOUND: 404,
  NOT_IMPLEMENTED: 501,
  PAYLOAD_TOO_LARGE: 413,
  PRECONDITION_FAILED: 412,
  REQUEST_TIMEOUT: 408,
  SERVICE_UNAVAILABLE: 503,
  TOO_MANY_REQUESTS: 429,
  UNAUTHORIZED: 401,
  UNPROCESSABLE_ENTITY: 422,
  UNSUPPORTED_MEDIA_TYPE: 415,
};

function parseHttpStatuses() {
  // @ref LLP 0199#sequencing-guidance-not-a-schedule — the reviewed family
  // table moved with the server's extracted test owner.
  const source = readFileSync(join(root, 'crates/snapback/src/server/tests.rs'), 'utf8');
  const families = new Map();
  for (const match of source.matchAll(/const\s+([A-Z0-9_]+):\s*&\[&str\]\s*=\s*&\[(.*?)\];/gsu)) {
    families.set(match[1], [...match[2].matchAll(/"(SNAPBACK_[A-Z0-9_]+)"/gu)].map((item) => item[1]));
  }
  const statuses = new Map();
  // StatusCode/family tuples occur only in the reviewed HTTP status table;
  // matching the tuples themselves avoids depending on rustfmt's wrapping of
  // the table's nested slice type.
  for (const match of source.matchAll(/\(\s*StatusCode::([A-Z_]+)\s*,\s*([A-Z0-9_]+)\s*\)/gu)) {
    const status = HTTP_STATUS_NUMBERS[match[1]];
    if (!status) continue;
    for (const code of families.get(match[2]) ?? []) statuses.set(code, status);
  }
  for (const match of source.matchAll(/\(\s*(\d{3})\s*,\s*&\[\s*"(SNAPBACK_[A-Z0-9_]+)"\s*\]\s*\)/gu)) {
    statuses.set(match[2], Number(match[1]));
  }
  return statuses;
}

function headingSlug(text) {
  const plain = text
    .replace(/`([^`]*)`/gu, '$1')
    .replace(/!\[([^\]]*)\]\([^)]*\)/gu, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/gu, '$1')
    .replace(/[*_~]/gu, '')
    .trim();
  return plain
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s+/gu, '-') || 'section';
}

function guideAnchors() {
  const anchors = new Map();
  const headingAnchors = new Map();
  // @ref LLP 0223#tickets — eval-run transcripts are retained evidence of
  // the retrieval protocol, not retrieval targets: a code mentioned in a
  // transcript must not capture (or alphabetically demote) the guide anchor
  // an agent is routed to when the code fires.
  const paths = walk(join(root, 'guide'), (path) => (
    path.endsWith('.md')
    && !/^guide\/guide-flat(?:\.[a-z0-9-]+)?\.generated\.md$/.test(path)
    && !path.startsWith('guide/reference/')
    && !path.startsWith('guide/eval-runs/')
  ));
  for (const path of paths) {
    const source = readFileSync(join(root, path), 'utf8');
    const lines = source.split('\n');
    const seenSlugs = new Map();
    let anchor = null;
    let inFence = false;
    for (const line of lines) {
      if (/^```/u.test(line)) inFence = !inFence;
      const heading = inFence ? null : line.match(/^#{1,6}\s+(.+)$/u);
      if (heading) {
        const base = headingSlug(heading[1]);
        const count = seenSlugs.get(base) ?? 0;
        seenSlugs.set(base, count + 1);
        anchor = count === 0 ? base : `${base}-${count}`;
      }
      for (const match of line.matchAll(CODE_PATTERN)) {
        if (!anchor) continue;
        const values = anchors.get(match[0]) ?? new Set();
        const value = `/_snapback/${path}${anchor ? `#${anchor}` : ''}`;
        values.add(value);
        anchors.set(match[0], values);
        if (heading?.[1].includes(match[0])) {
          const preferred = headingAnchors.get(match[0]) ?? new Set();
          preferred.add(value);
          headingAnchors.set(match[0], preferred);
        }
      }
    }
  }
  return new Map([...anchors].map(([code, values]) => {
    const preferred = [...(headingAnchors.get(code) ?? [])].sort();
    const remaining = [...values].filter((value) => !preferred.includes(value)).sort();
    return [code, [...preferred, ...remaining]];
  }));
}

function sourceDigest(paths) {
  const hash = createHash('sha256');
  for (const path of paths) {
    hash.update(path).update('\0').update(readFileSync(join(root, path))).update('\0');
  }
  return `sha256:${hash.digest('hex')}`;
}

function escapeTable(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function renderMarkdown(registry) {
  const lines = [
    '---',
    'title: Diagnostic code registry',
    'id: reference.diagnostics',
    'order: 99',
    'audience: agent-first',
    'capabilities: []',
    `authorities: [${markdownAuthorities.join(', ')}]`,
    'examples: []',
    'status: current',
    'targets: [all]',
    'maturity: shipped',
    'reviewed: 2026-08-08',
    `reviewed-authorities-digest: ${authoritiesDigest(root, markdownAuthorities)}`,
    '---',
    '',
    generatedMarker,
    '',
    '# Diagnostic code registry',
    '',
    'This build-bound registry is generated from production Rust, JavaScript, and Swift sources. Use `snapback guide SNAPBACK_*` for an exact, bounded lookup before searching prose.',
    '',
    `**${registry.counts.codes.toLocaleString('en-US')} stable codes** from ${registry.counts.sourceFiles.toLocaleString('en-US')} production source files. The [machine-readable registry](./diagnostics-registry.json) carries every emitting site.`,
    '',
    '| Code | Subsystem | HTTP | Guide | First emitting site | Sites |',
    '| --- | --- | ---: | --- | --- | ---: |',
  ];
  for (const record of Object.values(registry.diagnostics)) {
    const guideTarget = record.guideAnchor?.replace('/_snapback/guide/', '../');
    const guide = guideTarget ? `[guide](${guideTarget})` : '—';
    const first = record.sites[0];
    const anchor = `<a id="diagnostic-${record.code.toLowerCase().replaceAll('_', '-')}"></a>`;
    lines.push(`| ${anchor}\`${record.code}\` | ${escapeTable(record.subsystem)} | ${record.httpStatus ?? '—'} | ${guide} | \`${first.file}:${first.line}\` | ${record.sites.length} |`);
  }
  return `${lines.join('\n')}\n`;
}

function renderTypes(codes) {
  return [
    '// Generated by scripts/generate-diagnostics-registry.mjs. Never hand-edit.',
    '// @ref LLP 0193#program — the client diagnostic vocabulary is source-complete and drift-checked.',
    'export type SnapbackDiagnosticCode =',
    ...codes.map((code, index) => (index === 0 ? `  '${code}'` : `  | '${code}'`)),
    ';',
    '',
  ].join('\n');
}

const byCode = collectSites();
const statuses = parseHttpStatuses();
const anchors = guideAnchors();
const codes = [...byCode.keys()].sort();
const diagnostics = {};
for (const code of codes) {
  const sites = byCode.get(code).sort((left, right) => (
    left.file.localeCompare(right.file) || left.line - right.line || left.column - right.column
  ));
  const httpStatus = statuses.get(code) ?? null;
  const guide = anchors.get(code) ?? [];
  diagnostics[code] = {
    code,
    subsystem: subsystemFor(code, sites),
    sites,
    httpStatus,
    httpStatusClass: httpStatus === null ? null : `${Math.floor(httpStatus / 100)}xx`,
    guideAnchor: guide[0] ?? null,
    guideAnchors: guide,
  };
}
const inputPaths = [
  'scripts/generate-diagnostics-registry.mjs',
  ...diagnosticCatalogPaths,
  'scripts/guide-lib.mjs',
  ...productionPaths,
  ...walk(join(root, 'guide'), (path) => (
    path.endsWith('.md')
    && !/^guide\/guide-flat(?:\.[a-z0-9-]+)?\.generated\.md$/.test(path)
    && !path.startsWith('guide/reference/')
  )),
].sort();
const registry = {
  schemaVersion: 'snapback-diagnostics-registry.v1',
  generatedBy: 'scripts/generate-diagnostics-registry.mjs',
  buildIdentity: { sourceDigest: sourceDigest(inputPaths) },
  limits: { lookupBytes: 16_384 },
  counts: {
    codes: codes.length,
    sourceFiles: productionPaths.length,
    emittingSites: Object.values(diagnostics).reduce((total, record) => total + record.sites.length, 0),
    httpClassified: Object.values(diagnostics).filter((record) => record.httpStatus !== null).length,
    guideAnchored: Object.values(diagnostics).filter((record) => record.guideAnchor !== null).length,
  },
  diagnostics,
};
const rendered = new Map([
  [outputs.registry, `${JSON.stringify(registry, null, 2)}\n`],
  [outputs.markdown, renderMarkdown(registry)],
  [outputs.types, renderTypes(codes)],
]);

const stale = [];
for (const [path, expected] of rendered) {
  const absolute = join(root, path);
  const actual = existsSync(absolute) ? readFileSync(absolute, 'utf8') : null;
  if (actual !== expected) stale.push(path);
  if (!check) writeFileSync(absolute, expected);
}
if (check && stale.length > 0) {
  for (const path of stale) console.error(`[diagnostics-registry] stale: ${path}`);
  console.error('[diagnostics-registry] run node scripts/generate-diagnostics-registry.mjs');
  process.exit(1);
}
console.log(`[diagnostics-registry] ${check ? 'ok' : 'wrote'} — ${codes.length} codes, ${registry.counts.emittingSites} sites, ${registry.counts.httpClassified} HTTP-classified`);
