#!/usr/bin/env node
// Generate the build-bound diagnostics vocabulary, its Guide projection, and
// the public TypeScript code union. Output is sorted and carries no wall-clock
// value, so identical inputs always produce identical bytes.
// A diagnostic emission is a whole outer-string code literal or a leading
// outer-string `CODE:` message prefix (optionally `WARNING|ERROR|INFO CODE:`).
// A token nested inside a larger string
// counts only when that enclosing string is executable/generated source whose
// local syntax constructs or assigns a diagnostic, or SQL that writes it to an
// explicit diagnostic/error-code column. Environment-variable access,
// declarations/tables, message references, comments, comparisons, Rust match
// patterns, prefix checks, and code catalogues are excluded per site. Tokens
// ending in `_` are incomplete family prefixes, never codes. For a real emitter
// the syntax cannot prove, put `diagnostics-registry: emission SNAPBACK_X` in a
// comment on that line or before the statement. When a dynamic emitter never
// contains the complete spelling, put that same named marker immediately
// before the statement; the registry attaches a synthetic emission site to the
// statement rather than publishing the marker-comment coordinate. For
// a reference-only site whose syntax is otherwise ambiguous, put
// `diagnostics-registry: reference-only` in a comment on that line or the
// immediately preceding line; never mark a line that also emits. To reserve a
// spelling whose concrete emitter is dynamic, or a retired spelling in the
// stable vocabulary, use `diagnostics-registry: reserved SNAPBACK_X` there;
// reservations are published with their own site kind and do not count as
// emissions. Closed code-literal Sets/arrays in shipped client packages count
// as `received` vocabulary when the table flows to a `.has(code)` or
// `.includes(code)` dispatch membership test. Ambiguous receive tables use
// `diagnostics-registry: received SNAPBACK_X` on the literal line instead.
// Object-literal keys passed to known secret/environment writers and keys in
// spawned-process `env: { ... }` options are environment writes. For a custom
// writer the classifier cannot recognize, put
// `diagnostics-registry: environment SNAPBACK_X` on the write or immediately
// preceding line.
// @ref LLP 0193#program — D1's complete source inventory is the substrate for
// exact error lookup and typed client diagnostics.

