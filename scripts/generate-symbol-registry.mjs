function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function repoPath(path) {
  return relative(root, path).split('\\').join('/');
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function readPublishedClosureVersion() {
  const closure = readJson(join(root, publishedClosurePath));
  if (
    closure.schemaVersion !== 'snapback-published-closure.v1'
    || !/^\d+\.\d+\.\d+$/u.test(closure.newestPublished ?? '')
  ) {
    throw new Error(`${publishedClosurePath} does not carry a valid newestPublished closure version`);
  }
  return closure.newestPublished;
}

function targetAt(condition, target) {
  if (typeof target === 'string') return condition === 'default' ? target : null;
  if (target === null || typeof target !== 'object') return null;
  if (typeof target[condition] === 'string') return target[condition];
  return null;
}

function moduleName(packageName, subpath) {
  return subpath === '.' ? packageName : `${packageName}/${subpath.slice(2)}`;
}

function pageStem(packageName, subpath) {
  const packageStem = packageName.replace(/^@/u, '').replaceAll('/', '-');
  return subpath === '.'
    ? packageStem
    : `${packageStem}--${subpath.slice(2).replaceAll('/', '-')}`;
}

function pageId(packageName, subpath) {
  return `reference.api.${moduleName(packageName, subpath)}`
    .toLowerCase()
    .replace(/^reference\.api\.@/u, 'reference.api.')
    .split(/[^a-z0-9]+/u)
    .filter(Boolean)
    .join('.');
}

function publicModules() {
  const modules = [];
  for (const scope of scopes) {
    const manifestPath = join(root, scope.manifest);
    const manifest = readJson(manifestPath);
    for (const [subpath, target] of Object.entries(manifest.exports ?? {}).sort()) {
      if (scope.exports !== 'all' && !scope.exports.includes(subpath)) continue;
      const typesTarget = targetAt('types', target);
      if (typesTarget === null) continue;
      const runtimeCondition = targetAt('import', target) !== null
        ? 'import'
        : targetAt('require', target) !== null
          ? 'require'
          : targetAt('default', target) !== null
            ? 'default'
            : null;
      const runtimeTarget = runtimeCondition === null ? null : targetAt(runtimeCondition, target);
      if (runtimeTarget === null && scope.typeOnly !== true) {
        throw new Error(`${scope.manifest} export ${subpath} has types but no applicable runtime target`);
      }
      if (runtimeTarget !== null && scope.typeOnly === true) {
        throw new Error(`${scope.manifest} export ${subpath} is declared type-only but has a runtime target`);
      }
      const conditionalRuntimeTargets = Object.fromEntries(
        ['import', 'require', 'default']
          .map((condition) => [condition, targetAt(condition, target)])
          .filter(([, value]) => value !== null)
          .map(([condition, value]) => [condition, repoPath(resolve(dirname(manifestPath), value))]),
      );
      const applicableConditions = Object.entries(conditionalRuntimeTargets)
        .filter(([, path]) => runtimeTarget !== null && path === repoPath(resolve(dirname(manifestPath), runtimeTarget)))
        .map(([condition]) => condition);
      modules.push({
        package: manifest.name,
        packageVersion: manifest.version,
        subpath,
        module: moduleName(manifest.name, subpath),
        manifest: scope.manifest,
        typesTarget: repoPath(resolve(dirname(manifestPath), typesTarget)),
        runtimeCondition,
        runtimeTarget: runtimeTarget === null
          ? null
          : repoPath(resolve(dirname(manifestPath), runtimeTarget)),
        conditionalRuntimeTargets,
        parity: {
          applicableConditions,
          excludedConditions: Object.entries(conditionalRuntimeTargets)
            .filter(([, path]) => runtimeTarget !== null && path !== repoPath(resolve(dirname(manifestPath), runtimeTarget)))
            .map(([condition, path]) => ({
              condition,
              target: path,
              reason: 'Condition selects a different public surface with its own typed package subpath; this declaration follows the primary import surface.',
            })),
        },
        page: `guide/reference/${pageStem(manifest.name, subpath)}.md`,
      });
    }
  }
  return modules;
}

function resolveAlias(checker, symbol) {
  return symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
}

function symbolKind(symbol) {
  const flags = symbol.flags;
  if (flags & ts.SymbolFlags.Class) return 'class';
  if (flags & ts.SymbolFlags.Function) return 'function';
  if (flags & ts.SymbolFlags.Interface) return 'interface';
  if (flags & ts.SymbolFlags.TypeAlias) return 'type-alias';
  if (flags & ts.SymbolFlags.Enum) return 'enum';
  if (flags & ts.SymbolFlags.Module) return 'namespace';
  if (flags & (ts.SymbolFlags.Variable | ts.SymbolFlags.BlockScopedVariable)) return 'constant';
  return 'declaration';
}

function documentation(checker, symbol) {
  const text = ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim();
  const tags = symbol.getJsDocTags(checker).map((tag) => ({
    name: tag.name,
    text: Array.isArray(tag.text)
      ? tag.text.map((part) => part.text).join('')
      : (tag.text ?? ''),
  }));
  return { text, tags };
}

function sourceRecord(node) {
  const source = node.getSourceFile();
  const start = source.getLineAndCharacterOfPosition(node.getStart(source));
  const end = source.getLineAndCharacterOfPosition(node.getEnd());
  return {
    file: repoPath(source.fileName),
    line: start.line + 1,
    column: start.character + 1,
    endLine: end.line + 1,
  };
}

function declarationText(node) {
  return node.getText(node.getSourceFile()).trim();
}

function memberKey(node, index) {
  if (ts.isConstructorDeclaration(node)) return 'constructor';
  if (ts.isCallSignatureDeclaration(node)) return 'call';
  if (ts.isConstructSignatureDeclaration(node)) return 'construct';
  if (ts.isIndexSignatureDeclaration(node)) return 'index';
  if (node.name) return node.name.getText(node.getSourceFile());
  return `member-${index + 1}`;
}

function memberKind(node) {
  if (ts.isConstructorDeclaration(node)) return 'constructor';
  if (ts.isMethodDeclaration(node) || ts.isMethodSignature(node)) return 'method';
  if (ts.isPropertyDeclaration(node) || ts.isPropertySignature(node)) return 'property';
  if (ts.isGetAccessorDeclaration(node)) return 'getter';
  if (ts.isSetAccessorDeclaration(node)) return 'setter';
  if (ts.isCallSignatureDeclaration(node)) return 'call-signature';
  if (ts.isConstructSignatureDeclaration(node)) return 'construct-signature';
  if (ts.isIndexSignatureDeclaration(node)) return 'index-signature';
  return 'member';
}

function membersFor(checker, declarations, parentIdentity) {
  const groups = new Map();
  for (const declaration of declarations) {
    if (!('members' in declaration) || declaration.members === undefined) continue;
    for (const [index, member] of [...declaration.members].entries()) {
      const name = memberKey(member, index);
      const key = `${memberKind(member)}:${name}`;
      if (!groups.has(key)) groups.set(key, { name, kind: memberKind(member), nodes: [] });
      groups.get(key).nodes.push(member);
    }
  }
  return [...groups.values()].map(({ name, kind, nodes }) => {
    const memberSymbol = nodes[0].name ? checker.getSymbolAtLocation(nodes[0].name) : null;
    const signatures = nodes.map(declarationText);
    return {
      identity: `${parentIdentity}.${name}`,
      name,
      kind,
      signature: signatures.join('\n'),
      overloads: signatures.length > 1 ? signatures : [],
      documentation: memberSymbol ? documentation(checker, memberSymbol) : { text: '', tags: [] },
      sources: nodes.map(sourceRecord),
    };
  });
}

function anchorFor(identity, name) {
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/gu, '-').replace(/^-|-$/gu, '') || 'default';
  return `symbol-${slug}-${sha256(identity).slice(0, 10)}`;
}

function createRegistry(modules) {
  const program = ts.createProgram({
    rootNames: modules.map((entry) => join(root, entry.typesTarget)),
    options: {
      module: ts.ModuleKind.NodeNext,
      moduleResolution: ts.ModuleResolutionKind.NodeNext,
      target: ts.ScriptTarget.ESNext,
      skipLibCheck: true,
      allowJs: false,
      noEmit: true,
    },
  });
  const checker = program.getTypeChecker();
  const diagnostics = ts.getPreEmitDiagnostics(program).filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
  if (diagnostics.length > 0) {
    throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
      getCanonicalFileName: (fileName) => fileName,
      getCurrentDirectory: () => root,
      getNewLine: () => '\n',
    }));
  }

  const symbols = [];
  const moduleRecords = [];
  for (const moduleEntry of modules) {
    const source = program.getSourceFile(join(root, moduleEntry.typesTarget));
    if (!source) throw new Error(`TypeScript did not load ${moduleEntry.typesTarget}`);
    const moduleSymbol = checker.getSymbolAtLocation(source);
    if (!moduleSymbol) throw new Error(`TypeScript found no module symbol for ${moduleEntry.typesTarget}`);
    const moduleSymbolIds = [];
    for (const exported of checker.getExportsOfModule(moduleSymbol).sort((left, right) => left.name.localeCompare(right.name))) {
      const target = resolveAlias(checker, exported);
      const declarations = target.getDeclarations() ?? exported.getDeclarations() ?? [];
      const identity = `npm:${moduleEntry.module}#${exported.name}`;
      const isRuntime = Boolean(target.flags & ts.SymbolFlags.Value);
      const signatures = declarations.map(declarationText);
      const symbol = {
        identity,
        originIdentity: `${repoPath(declarations[0]?.getSourceFile().fileName ?? source.fileName)}#${target.name}`,
        anchor: anchorFor(identity, exported.name),
        name: exported.name,
        package: moduleEntry.package,
        module: moduleEntry.module,
        moduleSubpath: moduleEntry.subpath,
        kind: `${isRuntime ? 'runtime' : 'type'}-${symbolKind(target)}`,
        runtime: isRuntime
          ? { kind: 'value', exportNames: [exported.name], conditions: moduleEntry.parity.applicableConditions }
          : { kind: 'type-only', exportNames: [], conditions: [] },
        signature: signatures.join('\n'),
        overloads: signatures.length > 1 ? signatures : [],
        members: membersFor(checker, declarations, identity),
        documentation: documentation(checker, target),
        source: declarations.length > 0 ? sourceRecord(declarations[0]) : sourceRecord(source),
        sources: declarations.map(sourceRecord),
        publicDeclaration: { file: moduleEntry.typesTarget, exportName: exported.name },
        closure: {
          status: 'build-bound',
          note: moduleEntry.runtimeTarget === null
            ? 'Derived from this checkout public type-only declaration; runtime parity is not applicable.'
            : 'Derived from this checkout public declaration and applicable runtime export target.',
        },
      };
      symbols.push(symbol);
      moduleSymbolIds.push(identity);
    }
    moduleRecords.push({ ...moduleEntry, symbolIds: moduleSymbolIds });
  }

  // @ref LLP 0187#t5--guide-truthfulness-against-the-published-closure —
  // public version labels come from the checked-in publication closure, while
  // source-manifest versions remain separately labeled checkout facts.
  const publishedClosureVersion = readPublishedClosureVersion();
  const inputPaths = new Set([
    'scripts/generate-symbol-registry.mjs',
    'scripts/guide-lib.mjs',
    'scripts/symbol-lifecycle.mjs',
    publishedClosurePath,
    lifecyclePath,
    lifecycleSchemaPath,
  ]);
  for (const moduleEntry of modules) {
    inputPaths.add(moduleEntry.manifest);
    inputPaths.add(moduleEntry.typesTarget);
    if (moduleEntry.runtimeTarget !== null) inputPaths.add(moduleEntry.runtimeTarget);
    for (const path of Object.values(moduleEntry.conditionalRuntimeTargets)) inputPaths.add(path);
  }
  const sourceDigest = sha256([...inputPaths].sort().map((path) => (
    `${path}\0${readFileSync(join(root, path))}\0`
  )).join(''));
  const exact = {};
  for (const symbol of symbols) {
    for (const name of [symbol.name, ...symbol.members.map((member) => `${symbol.name}.${member.name}`)]) {
      if (!exact[name]) exact[name] = [];
      exact[name].push(symbol.identity);
    }
  }
  const packageNames = [...new Set(modules.map((entry) => entry.package))].sort();
  return {
    schemaVersion: 'snapback-symbol-registry.v1',
    generatedBy: 'scripts/generate-symbol-registry.mjs',
    buildIdentity: {
      sourceDigest: `sha256:${sourceDigest}`,
      publishedClosureVersion,
      packageVersions: Object.fromEntries(packageNames.map((name) => [
        name,
        publishedClosureVersion,
      ])),
      sourceManifestVersions: Object.fromEntries(packageNames.map((name) => [
        name,
        modules.find((entry) => entry.package === name).packageVersion,
      ])),
    },
    limits: {
      moduleMarkdownBytes: modulePageBudgetBytes,
      indexMarkdownBytes: indexPageBudgetBytes,
      lookupBytes: 16_384,
    },
    scope: {
      packages: scopes.map((scope) => scope.manifest),
      handlerContext: {
        status: 'included-published-type-only-declaration',
        module: '@expo/snapback-codegen/ctx',
        declaration: 'packages/snapback-codegen/ctx.d.mts',
        runtimeParity: 'exempt-type-only',
      },
    },
    modules: moduleRecords,
    symbols,
    lookup: { exact },
  };
}

async function checkRuntimeParity(registry) {
  const errors = [];
  const symbolsByModule = new Map();
  for (const symbol of registry.symbols) {
    if (!symbolsByModule.has(symbol.module)) symbolsByModule.set(symbol.module, []);
    symbolsByModule.get(symbol.module).push(symbol);
  }
  for (const moduleRecord of registry.modules) {
    if (moduleRecord.runtimeTarget === null) {
      const runtimeSymbols = (symbolsByModule.get(moduleRecord.module) ?? [])
        .filter((symbol) => symbol.runtime.kind !== 'type-only');
      for (const symbol of runtimeSymbols) {
        errors.push(`${moduleRecord.module}: type-only module exported value-space symbol '${symbol.name}'`);
      }
      continue;
    }
    let runtimeNames;
    if (moduleRecord.runtimeCondition === 'require') {
      // @ref LLP 0194#acceptance — require-condition parity must observe the
      // CommonJS value consumers receive, including its module.exports root,
      // rather than a Node-version-dependent synthetic ESM namespace.
      const target = join(root, moduleRecord.runtimeTarget);
      const probe = spawnSync(
        process.execPath,
        ['--input-type=commonjs', '--eval', requireRuntimeProbe, target],
        {
          cwd: root,
          encoding: 'utf8',
          stdio: ['ignore', 'pipe', 'pipe', 'pipe'],
          timeout: 30_000,
        },
      );
      if (probe.status !== 0) {
        const cause = probe.error?.message
          ?? probe.stderr?.trim()
          ?? (probe.signal === null ? `exit ${probe.status}` : `signal ${probe.signal}`);
        errors.push(`${moduleRecord.module}: could not require ${moduleRecord.runtimeTarget}: ${cause}`);
        continue;
      }
      let observed;
      try {
        observed = JSON.parse(probe.output[3]);
      } catch (error) {
        errors.push(`${moduleRecord.module}: require probe returned invalid runtime export data: ${error.message}`);
        continue;
      }
      if (!Array.isArray(observed.exportNames) || typeof observed.moduleExportsType !== 'string') {
        errors.push(`${moduleRecord.module}: require probe returned invalid runtime export data`);
        continue;
      }
      if (observed.moduleExportsType === 'undefined') {
        errors.push(`${moduleRecord.module}: require runtime returned undefined module.exports`);
        continue;
      }
      runtimeNames = [...new Set([
        ...observed.exportNames,
        // A successful require returns module.exports itself. Node's ESM
        // interoperability also exposes that same root value as default.
        'default',
        'module.exports',
      ])].filter((name) => name !== '__esModule').sort();
    } else {
      const url = pathToFileURL(join(root, moduleRecord.runtimeTarget));
      url.searchParams.set('snapback-symbol-registry', registry.buildIdentity.sourceDigest.slice(-16));
      let runtime;
      try {
        runtime = await import(url.href);
      } catch (error) {
        errors.push(`${moduleRecord.module}: could not import ${moduleRecord.runtimeTarget}: ${error.message}`);
        continue;
      }
      runtimeNames = Object.keys(runtime).filter((name) => name !== '__esModule').sort();
    }
    const declaredValues = (symbolsByModule.get(moduleRecord.module) ?? [])
      .filter((symbol) => symbol.runtime.kind === 'value')
      .flatMap((symbol) => symbol.runtime.exportNames)
      .sort();
    for (const name of declaredValues) {
      if (!runtimeNames.includes(name)) {
        errors.push(`${moduleRecord.module}: declared value '${name}' is absent from ${moduleRecord.runtimeCondition} runtime exports`);
      }
    }
    for (const name of runtimeNames) {
      if (!declaredValues.includes(name)) {
        errors.push(`${moduleRecord.module}: public ${moduleRecord.runtimeCondition} runtime export '${name}' has no value-space registry entry`);
      }
    }
  }
  return errors;
}

function checkHandlerContextOwnership(registry) {
  const errors = [];
  const ownerModule = '@expo/snapback-codegen/ctx';
  const ownerSymbols = registry.symbols.filter((symbol) => symbol.module === ownerModule);
  if (ownerSymbols.length === 0) {
    return [`${ownerModule}: published declaration contributed no registry symbols`];
  }
  const emitterPath = 'packages/snapback-codegen/index.mjs';
  const emitter = readFileSync(join(root, emitterPath), 'utf8');
  if (!emitter.includes("const CTX_DECLARATION_MODULE = '@expo/snapback-codegen/ctx';")) {
    errors.push(`${emitterPath}: generated API template does not name the published ctx owner`);
  }
  if (!emitter.includes("export type * from '${CTX_DECLARATION_MODULE}';")) {
    errors.push(`${emitterPath}: generated API template does not re-export the published ctx owner`);
  }
  for (const symbol of ownerSymbols) {
    const duplicate = new RegExp(
      `export\\s+(?:declare\\s+)?(?:interface|type|class|enum|namespace|const|function)\\s+${symbol.name}\\b`,
      'u',
    );
    if (duplicate.test(emitter)) {
      errors.push(`${emitterPath}: generated API template redeclares stable ctx owner ${symbol.identity}`);
    }
  }
  for (const name of [
    'GeneratedQueryBuilder',
    'GeneratedQueryDatabase',
    'GeneratedMutationDatabase',
    'GeneratedQueryContext',
    'GeneratedMutationContext',
    'GeneratedActionContext',
  ]) {
    const duplicateGeneric = new RegExp(
      `export\\s+interface\\s+${name}\\b`,
      'u',
    );
    if (duplicateGeneric.test(emitter)) {
      errors.push(`${emitterPath}: ${name} redeclares the generic ctx contract instead of instantiating its owner`);
    }
  }
  for (const expected of [
    'GeneratedQueryBuilder<Table extends GeneratedReadableTableName> = QueryBuilder<GeneratedHandlerSchema, Table>',
    'GeneratedQueryDatabase = QueryDatabase<GeneratedHandlerSchema>',
    'GeneratedMutationDatabase = MutationDatabase<GeneratedHandlerSchema>',
    'GeneratedQueryContext<Auth extends GeneratedAuthContext = GeneratedAuthContext> = QueryContext<',
    'GeneratedMutationContext<Auth extends GeneratedAuthContext = GeneratedAuthContext> = MutationContext<',
    'GeneratedActionContext<Auth extends GeneratedAuthContext = GeneratedAuthContext> = ActionContext<',
  ]) {
    if (!emitter.includes(expected)) {
      errors.push(`${emitterPath}: generated API template is missing ctx-owner instantiation ${expected}`);
    }
  }
  return errors;
}

function yamlArray(values) {
  return `[${values.join(', ')}]`;
}

function lifecycleLines(registry, symbol) {
  const facts = symbol.lifecycle;
  if (!facts) return [];
  const lines = [];
  if (facts.replaces) {
    const predecessor = registry.removedSymbols.find(({ identity }) => identity === facts.replaces);
    const version = predecessor?.lifecycle.removedIn;
    lines.push(`Replaces \`${facts.replaces}\`${version ? ` (renamed in ${version})` : ''}.`);
  }
  if (facts.replacedBy) lines.push(`Replaced by \`${facts.replacedBy}\`.`);
  return lines;
}

function removedSymbolLine(symbol) {
  const replacement = symbol.lifecycle.replacedBy
    ? `; replaced by \`${symbol.lifecycle.replacedBy}\``
    : '';
  return `- \`${symbol.identity}\` — removed in ${symbol.lifecycle.removedIn}${replacement}`;
}

