import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { mergePagedArchive } from './pagination.mjs';

const readJson = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const artifacts = readJson('./snapback/generated/artifacts.json');
const functions = readJson('./snapback/generated/functions.manifest.json');
const schema = readJson('./snapback/generated/schema.manifest.json');
const appSource = readFileSync(new URL('./App.tsx', import.meta.url), 'utf8');
const functionSource = readFileSync(new URL('./snapback/functions.mjs', import.meta.url), 'utf8');
const schemaSource = readFileSync(new URL('./snapback/schema.mjs', import.meta.url), 'utf8');
const runtimeAcceptance = readFileSync(new URL('./acceptance.mjs', import.meta.url), 'utf8');
const packageManifest = readJson('./package.json');
const expoManifest = readJson('./app.json');
const instructions = readFileSync(new URL('./AGENTS.md', import.meta.url), 'utf8');
const carrierSource = readFileSync(new URL('./carrier.mjs', import.meta.url), 'utf8');

assert.equal(artifacts.artifactKind, 'artifactIndex');
assert.equal(schema.auth.mode, 'sessions');
assert.deepEqual(functions.functions.map((fn) => fn.name).sort(), ['createEntry', 'liveFeed', 'olderFeedPage']);
assert.deepEqual(functions.assetUploadIntents.map((intent) => intent.exportedName).sort(), ['feedPhotoUpload', 'privatePhotoUpload']);
const publicIntent = functions.assetUploadIntents.find((intent) => intent.exportedName === 'feedPhotoUpload');
const privateIntent = functions.assetUploadIntents.find((intent) => intent.exportedName === 'privatePhotoUpload');
assert.equal(publicIntent.delivery.kind, 'public-immutable');
assert.equal(privateIntent.delivery.kind, 'private-strict');
assert.deepEqual(publicIntent.image.variants.map((variant) => variant.key), ['thumb', 'display']);
assert.match(functionSource, /location:\s*'strip'/);
assert.match(functionSource, /ctx\.assets\.attach/);
assert.match(schemaSource, /v\.assetRef\(\{ upload: 'feedPhotoUpload' \}\)/);
assert.match(schemaSource, /assetSharing\(\{ kind: 'public-read' \}\)/);
assert.match(schemaSource, /index\('by_page_key', \['pageKey'\], \{ unique: true \}\)/);
assert.match(functionSource, /ltFilter\('pageKey', arg\('before'\)\)/);
assert.doesNotMatch(functionSource, /ltFilter\('createdAt'/);
assert.match(appSource, /useSnapbackCommand\(app\.commands\.publishEntry\)/);
assert.match(appSource, /useSnapbackAssetImage/);
assert.match(appSource, /api\.olderFeedPage/);
assert.match(appSource, /onEndReached=\{loadOlder\}/);
assert.match(appSource, /oldest\.pageKey/);
const entry = (ordinal) => ({ _id: `entry-${ordinal}`, pageKey: String(ordinal).padStart(4, '0') });
const previousHead = [12, 11, 10, 9, 8, 7].map(entry);
const nextHead = [13, 12, 11, 10, 9, 8].map(entry);
const priorArchive = [6, 5, 4, 3, 2, 1].map(entry);
const rolledArchive = mergePagedArchive({ archive: priorArchive, head: nextHead, previousHead });
assert.deepEqual(rolledArchive.map((row) => row._id), [7, 6, 5, 4, 3, 2, 1].map((ordinal) => `entry-${ordinal}`));
assert.equal(new Set([...nextHead, ...rolledArchive].map((row) => row._id)).size, 13);
assert.equal(mergePagedArchive({ archive: rolledArchive, head: nextHead }), rolledArchive, 'stable deliveries preserve archive identity');
assert.match(appSource, /registerExpoFileSystemRqsFiles/);
assert.deepEqual(expoManifest.expo.platforms, ['ios', 'android', 'web']);
assert.match(packageManifest.scripts.prove, /^snapback verify snapback /);
assert.match(instructions, /only done-oracle/);
assert.equal(packageManifest.scripts['test:live'], undefined);
assert.equal(packageManifest.scripts['carry:headless'], 'node carrier.mjs headless');
assert.equal(packageManifest.scripts['carry:web-browser'], 'node carrier.mjs web-browser');
assert.equal(packageManifest.scripts['carry:native-simulator'], 'node carrier.mjs native-simulator');
assert.match(instructions, /carry:native-simulator/);
assert.match(carrierSource, /bundleId:\s*'host\.exp\.Exponent'/);
assert.match(carrierSource, /driveUrl:\s*'exp:/);
assert.match(runtimeAcceptance, /'wait', '--ready-file', readyFile/);
assert.match(runtimeAcceptance, /'--level', 'application', '--timeout-ms', '60000'/);
assert.match(runtimeAcceptance, /applicationReadyObserved: true/);
assert.match(runtimeAcceptance, /firstQueryRetries: 0/);
assert.doesNotMatch(runtimeAcceptance, /generated-and-loaded/);
assert.match(runtimeAcceptance, /createAssetClient\(client\)/);
assert.match(runtimeAcceptance, /loaded: loadedIdentity/);
console.log('media-feed static coherence: typed upload custody, renditions, delivery choice, unique retained live paging with displaced-head rollover, image rendering, and proof command are coherent');
