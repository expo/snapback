// Workspace-only helper computing the client's generated search-contract pin
// from the descriptor pipeline itself (never published; the committed output
// is search-contract.generated.mjs).
//
// The pin is the v2 args-contract witness of `defineSearchQuery`'s complete
// argument contract — computed through @expo/snapback-codegen's own
// defineSearchQuery + effectiveArgsContract + argsContractHash path, so the
// constant can never drift from what codegen stamps on generated search
// references without the search-pin conformance test failing.
//
// @ref LLP 0131#identity-and-hashing — cascade item 2 (generated pin, coded
// skew refusal); the runtime comparison lives in index.mjs.

export const SEARCH_CONTRACT_GENERATION = 'snapback:function-args:v2';

export async function computeSearchContractPin() {
  // Relative workspace imports: this helper is deliberately unpublished and
  // @expo/snapback-client declares no codegen dependency; the committed generated
  // constant is what ships.
  const [{ defineSchema, defineTable, defineSearchQuery, v }, contracts] = await Promise.all([
    import('../snapback-codegen/define.mjs'),
    import('../snapback-codegen/result-contracts.mjs'),
  ]);
  const table = defineTable({
    title: v.string(),
  }).searchIndex('pin', {
    semanticVersion: 'pin-v1',
    textFields: { title: { weight: 1, classification: 'public' } },
    visibility: { kind: 'public-read' },
  });
  defineSchema({ pinRows: table });
  const definition = defineSearchQuery({ table, index: 'pin' });
  return contracts.argsContractHash(contracts.effectiveArgsContract(definition.args));
}

export async function searchContractPinSource() {
  const hash = await computeSearchContractPin();
  return [
    '// Generated by packages/snapback-client/generate-search-contract.mjs.',
    '// Do not edit by hand — regenerate; the codegen search-pin conformance',
    '// test fails on drift (LLP 0131 identity cascade item 2).',
    `export const SEARCH_REQUEST_ARGS_CONTRACT_GENERATION = '${SEARCH_CONTRACT_GENERATION}';`,
    `export const SEARCH_REQUEST_ARGS_CONTRACT_HASH = '${hash}';`,
    '',
  ].join('\n');
}
