// @expo/snapback-vite Bun-runtime acceptance: run a real Vite dev server on
// Bun's node:http shim, relay a durable live stream through /__snapback, and
// prove a system-route WebSocket upgrade still fails closed.

import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { scaffoldApp } from '@expo/snapback-cli';
import { SnapbackClient } from '@expo/snapback-client';
import { snapbackDev } from './index.mjs';

assert.notEqual(
  typeof Bun,
  'undefined',
  'bun-relay.test.mjs must run under Bun; use `bun bun-relay.test.mjs`',
);
console.log(`bun-relay: Bun ${globalThis.Bun.version} runtime confirmed`);

const packageDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(packageDir, '..', '..');
const runtimeBinary = process.env.SNAPBACK_RUNTIME_BINARY
  ?? join(repoRoot, 'target', 'debug', 'snapback');
assert.ok(
  existsSync(runtimeBinary),
  `native snapback binary missing at ${runtimeBinary}; set SNAPBACK_RUNTIME_BINARY to a qualified binary`,
);

const ADA = 'user_ada';

async function eventually(check, { timeoutMs = 10_000, label = 'condition' } = {}) {
  const deadline = Date.now() + timeoutMs;
  let lastError = null;
  while (Date.now() < deadline) {
    try {
      const value = await check();
      if (value !== false) return value;
    } catch (error) {
      lastError = error;
    }
    await new Promise((resolveWait) => setTimeout(resolveWait, 100));
  }
  throw new Error(`timed out waiting for ${label}${lastError ? `: ${lastError.message}` : ''}`);
}

function expectWebSocketRefusal(url) {
  return new Promise((resolveRefusal, rejectRefusal) => {
    let opened = false;
    let settled = false;
    const socket = new WebSocket(url);
    const finish = (error = null) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) rejectRefusal(error);
      else resolveRefusal();
    };
    const timer = setTimeout(() => {
      try { socket.close(); } catch { /* timeout owns the failure */ }
      finish(new Error(`timed out waiting for refused WebSocket upgrade: ${url}`));
    }, 5_000);
    socket.addEventListener('open', () => {
      opened = true;
      try { socket.close(); } catch { /* the assertion owns the failure */ }
      finish(new Error(`refused WebSocket upgrade unexpectedly opened: ${url}`));
    }, { once: true });
    socket.addEventListener('error', () => {
      if (!opened) finish();
    }, { once: true });
    socket.addEventListener('close', () => {
      if (!opened) finish();
    }, { once: true });
  });
}

const root = realpathSync(mkdtempSync(join(tmpdir(), 'snapback-vite-bun-relay-')));
let viteServer = null;
let stream = null;
let readyFile = null;
try {
  const project = join(root, 'todo-contract');
  assert.equal(scaffoldApp(project).ok, true, 'temporary todo app scaffolds under Bun');
  const backend = join(project, 'snapback');

  // Snapback codegen deliberately requires Node 24's permission model. Keep
  // only generation in a Node child; managed lifecycle orchestration, Vite,
  // and the clients below all remain in this Bun process so the relay sits on
  // Bun's node:http shim.
  const generated = spawnSync(
    'node',
    [join(repoRoot, 'packages', 'snapback-codegen', 'index.mjs'), backend],
    { cwd: repoRoot, encoding: 'utf8' },
  );
  assert.equal(
    generated.status,
    0,
    `Node child failed to generate the Bun relay fixture:\n${generated.stdout}\n${generated.stderr}`,
  );
  const api = (await import(pathToFileURL(join(backend, 'generated', 'api.mjs')).href)).default;
  console.log('bun-relay: temporary app generated by the Node 24 child');

  const appRoot = join(root, 'app');
  mkdirSync(appRoot, { recursive: true });
  writeFileSync(join(appRoot, 'index.html'), '<!doctype html><title>snapback-vite Bun relay test</title>\n');

  const database = join(project, '.snapback', 'dev.sqlite3');
  readyFile = join(project, '.snapback', 'dev.ready.json');
  const events = [];
  const { createServer } = await import('vite');
  viteServer = await createServer({
    root: appRoot,
    configFile: false,
    logLevel: 'silent',
    plugins: [
      snapbackDev({
        server: {
          mode: 'managed',
          db: database,
          readyFile,
          runtimeBinary,
          stdio: 'ignore',
        },
        projectRoot: project,
        setup: { backendDirectory: backend },
        onEvent: (event) => events.push(event),
        logJson: false,
      }),
    ],
    server: { host: '127.0.0.1', port: 0, strictPort: false },
  });
  await viteServer.listen();
  const address = viteServer.httpServer.address();
  assert.ok(address && typeof address !== 'string', 'Vite reported its Bun-backed HTTP port');
  const origin = `http://127.0.0.1:${address.port}`;
  console.log('bun-relay: managed backend and real Bun-backed Vite server ready');

  const client = new SnapbackClient(`${origin}/__snapback`);
  stream = client.openLiveStream('bun_vite_ws');
  await stream.ready;
  await client.subscribeLive(api.listTodos, { connectionId: 'bun_vite_ws', userId: ADA });
  await client.mutate(api.createTodo, {
    args: { title: 'Pushed through Bun Vite relay' },
    userId: ADA,
  });
  const update = await stream.nextUpdate(10_000);
  assert.equal(update.kind, 'live_replace', `expected live_replace, received ${JSON.stringify(update)}`);
  console.log('bun-relay: durable live_replace arrived after a proxied mutation');

  await expectWebSocketRefusal(
    `${origin.replace(/^http/u, 'ws')}/__snapback/_snapback/api/inspect`,
  );
  assert.ok(
    events.some((event) => event.event === 'proxy-refused'
      && event.transport === 'websocket'
      && event.code === 'SNAPBACK_DEV_PROXY_ROUTE_REFUSED'),
    'the failed upgrade traversed the websocket allowlist refusal path',
  );
  console.log('bun-relay: websocket upgrade to a refused system route failed closed');

  await stream.close();
  stream = null;
  await viteServer.close();
  viteServer = null;
  await eventually(() => !existsSync(readyFile), { label: 'managed backend teardown' });
  console.log('bun-relay.test.mjs: Bun Vite websocket relay + 403 upgrade refusal pass');
} finally {
  try {
    await stream?.close();
  } catch {
    // best-effort cleanup after an earlier assertion failure
  }
  try {
    await viteServer?.close();
  } catch {
    // best-effort cleanup after an earlier assertion failure
  }
  if (readyFile) {
    try {
      await eventually(() => !existsSync(readyFile), {
        timeoutMs: 5_000,
        label: 'failed-test managed backend teardown',
      });
    } catch {
      // Vite lifecycle teardown already attempted; preserve the test failure.
    }
  }
  rmSync(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
}
