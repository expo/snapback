// Mounted-provider HMR generation handoff (LLP 0114 dated amendment
// 2026-08-05; issues/closed/20260803-react-hmr-reference-invalid.md).
//
// Regression shape: Metro/Vite HMR hot-replaces the generated api module
// while the mounted SnapbackProvider keeps the prepared binding admitted from
// the previous codegen generation. Hooks then present a valid new-generation
// reference to old-generation admission state, and pre-fix the strict
// SNAPBACK_REACT_REFERENCE_INVALID refusal threw uncaught through the render
// tree. The fix: in a POSITIVELY identified development environment the
// provider treats that exact split as a provider-boundary invalidation — it
// re-runs complete admission against the live deployment and swaps the
// binding's generation view atomically, showing a brief pending/refreshing
// frame meanwhile; if the rebind cannot complete it triggers a controlled dev
// reload with a clear console diagnostic. Foreign references and production
// builds keep the strict throw unchanged.

import assert from 'node:assert/strict';
import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';

import {
  createClientDevConsoleReporter,
  createClientDiagnosticsChannel,
} from '../snapback-client/client-diagnostics.mjs';
import {
  prepareReactBindingForClient,
  activeReactBindingDeploymentIdentity,
  classifyRegeneratedReactReference,
} from '../snapback-client/react-binding.mjs';
import { resultContractHash } from '../snapback-codegen/result-contracts.mjs';
import {
  SnapbackProvider,
  createSnapbackReactProvider,
  useSnapbackMutation,
  useSnapbackQuery,
} from './index.mjs';

globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const flush = () => new Promise((resolve) => setImmediate(resolve));

// No recovery path may leak an uncaught error or rejection. The collectors
// must still fail the process loudly (a swallowed top-level assertion would
// otherwise exit 0), so they set the exit code and log.
const uncaught = [];
const collectUncaught = (error) => {
  uncaught.push(error);
  console.error('hmr-generation-handoff.test.mjs uncaught:', error);
  process.exitCode = 1;
};
process.on('uncaughtException', collectUncaught);
process.on('unhandledRejection', collectUncaught);

const APP_ID = 'hmr-handoff-fixture';

const recordsContract = (fieldName) => Object.freeze({
  kind: 'records',
  record: Object.freeze({
    kind: 'object',
    fields: Object.freeze([
      Object.freeze({ name: 'id', required: true, value: { kind: 'string', maxBytes: 64 } }),
      Object.freeze({ name: fieldName, required: true, value: { kind: 'string', maxBytes: 256 } }),
    ]),
    allowExtra: false,
  }),
});
const mutationContract = Object.freeze({
  kind: 'value',
  value: Object.freeze({ kind: 'string', maxBytes: 256 }),
});

const definition = (name, kind, suffix, resultContract) => Object.freeze({
  artifactKind: 'functionReference',
  schemaVersion: 'snapback.v0',
  appId: APP_ID,
  id: `${APP_ID}:${name}`,
  name,
  kind,
  implementationHash: `sha256:impl-${name}-${suffix}`,
  argsContractHash: `sha256:args-${name}-${suffix}`,
  argsContract: { kind: 'object', fields: [] },
  resultContractHash: resultContractHash(resultContract),
  resultContract,
});

// Generation 1: the manifests the mounted binding admitted.
const timelineV1Contract = recordsContract('text');
const gen1 = {
  timeline: definition('timeline', 'LiveQuery', 'g1', timelineV1Contract),
  post: definition('post', 'Mutation', 'g1', mutationContract),
  about: definition('about', 'LiveQuery', 'shared', recordsContract('body')),
};
// Generation 2: codegen changed timeline's contract and post's args; about is
// regenerated byte-identically.
const timelineV2Contract = recordsContract('caption');
const gen2 = {
  timeline: definition('timeline', 'LiveQuery', 'g2', timelineV2Contract),
  post: definition('post', 'Mutation', 'g2', mutationContract),
  about: gen1.about,
};

const schemaManifest = (suffix) => Object.freeze({
  artifactKind: 'schemaManifest',
  schemaVersion: 'snapback.v0',
  appId: APP_ID,
  schemaHash: `sha256:schema-${suffix}`,
  ephemeralCollections: Object.freeze([]),
  tables: Object.freeze([]),
});
const functionsManifest = (suffix, functions) => Object.freeze({
  artifactKind: 'functionManifest',
  schemaVersion: 'snapback.v0',
  appId: APP_ID,
  bundleHash: `sha256:bundle-${suffix}`,
  inputsHash: `sha256:inputs-${suffix}`,
  functions: Object.freeze(functions),
});
const capabilityManifest = Object.freeze({
  artifactKind: 'capabilityManifest',
  schemaVersion: 'snapback.v0',
  targetProfileId: 'local-dev-sqlite-ibex',
  supportedCapabilities: Object.freeze(['live_subscriptions']),
});
const generations = {
  g1: {
    schema: schemaManifest('g1'),
    functions: functionsManifest('g1', [gen1.timeline, gen1.post, gen1.about]),
    capabilityManifest,
  },
  g2: {
    schema: schemaManifest('g2'),
    functions: functionsManifest('g2', [gen2.timeline, gen2.post, gen2.about]),
    capabilityManifest,
  },
};
const generationStamp = (manifest) => Object.freeze({
  schemaVersion: manifest.functions.schemaVersion,
  appId: APP_ID,
  schemaHash: manifest.schema.schemaHash,
  bundleHash: manifest.functions.bundleHash,
  inputsHash: manifest.functions.inputsHash,
});
// What the hot-replaced api module presents to hooks: the same reference
// content stamped with its own generation.
const apiReference = (def, manifest) => Object.freeze({
  ...def,
  expectedGeneration: generationStamp(manifest),
});

function createFakeClient(initialGeneration) {
  let served = initialGeneration;
  const liveHandles = [];
  const mutations = [];
  const diagnosticsChannel = createClientDiagnosticsChannel();
  const diagnosticsReporter = createClientDevConsoleReporter(diagnosticsChannel);
  const client = {
    liveQuery() {},
    diagnosticsChannel: () => diagnosticsChannel,
    async inspect() {
      return {
        targetProfileId: 'local-dev-sqlite-ibex',
        target: 'local-dev-sqlite-ibex',
        schema: served.schema,
        functions: served.functions,
        routeManifestHash: null,
        capabilityManifest: served.capabilityManifest,
      };
    },
    async authSession() { return { activeMode: 'dev' }; },
    registerAuthBarrierParticipant() { return async () => {}; },
    liveStreamManager() {
      return { close() {}, inspection() { return { socketDemand: 0 }; } };
    },
    async releaseConnection() { return { released: true }; },
    async mutate(ref, { args }) {
      mutations.push({ ref, args });
      return { result: `${ref.name}:${ref.implementationHash}` };
    },
    startLiveQuery(ref, options) {
      const current = { rows: [], connection: 'connecting', freshness: null, retention: null };
      let established = false;
      let resolveStarted = () => {};
      const started = new Promise((resolve) => { resolveStarted = resolve; });
      const handle = {
        function: ref.name,
        reference: ref,
        get current() { return established ? current : null; },
        started: () => started,
        dispose() {},
        settled: async () => {},
        emitAuthoritative(rows) {
          current.rows = rows;
          current.freshness = 'current';
          current.connection = 'live';
          established = true;
          options.onUpdate?.(rows, { kind: 'live_replace' });
          options.onConnectionChange?.('live');
          resolveStarted();
        },
      };
      liveHandles.push(handle);
      return Object.freeze(handle);
    },
    serve(generation) { served = generation; },
    disposeDiagnostics() {
      diagnosticsReporter.dispose();
      diagnosticsChannel.dispose();
    },
    inspection() { return { liveHandles, mutations, diagnosticsChannel }; },
  };
  return client;
}

async function waitFor(predicate, label, attempts = 400) {
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    if (predicate()) return;
    await act(async () => {
      await flush();
      await new Promise((resolve) => setTimeout(resolve, 5));
      await flush();
    });
  }
  assert.fail(`timed out waiting for ${label}`);
}

// ---------------------------------------------------------------------------
// 1. Positively identified dev environment: a regenerated reference against
//    the mounted provider performs an atomic generation handoff — the render
//    shows a refreshing/pending boundary frame (never a throw, never a frame
//    that pairs the new reference with old admission), and the unchanged
//    sibling query keeps full continuity.
// ---------------------------------------------------------------------------
{
  globalThis.__DEV__ = true;
  const client = createFakeClient(generations.g1);
  const binding = await prepareReactBindingForClient(client, {
    generatedManifest: generations.g1,
  });
  const provider = createSnapbackReactProvider(binding, {
    connectionId: 'hmr-a',
    developmentHmr: { timeoutMs: 5_000, pollIntervalMs: 0 },
    __diagnosticsChurnTransitionThreshold: 1,
    __diagnosticsChurnWindowMs: 2_000,
  });
  let timelineState = null;
  let aboutState = null;
  function Probe({ timelineRef, aboutRef }) {
    timelineState = useSnapbackQuery(timelineRef, {});
    aboutState = useSnapbackQuery(aboutRef, {});
    return null;
  }
  const timelineApiV1 = apiReference(gen1.timeline, generations.g1);
  const aboutApiV1 = apiReference(gen1.about, generations.g1);
  let renderer;
  await act(async () => {
    renderer = TestRenderer.create(React.createElement(
      SnapbackProvider,
      { provider },
      React.createElement(Probe, { timelineRef: timelineApiV1, aboutRef: aboutApiV1 }),
    ));
    await flush();
  });
  const [timelineHandleV1, aboutHandle] = client.inspection().liveHandles;
  await act(async () => {
    timelineHandleV1.emitAuthoritative([{ id: 't1', text: 'first' }]);
    aboutHandle.emitAuthoritative([{ id: 'a1', body: 'about' }]);
    await flush();
  });
  assert.equal(timelineState.status, 'ready');
  assert.equal(aboutState.status, 'ready');

  // Codegen ran, the local backend redeployed, and Metro hot-replaced the
  // api module while the provider stayed mounted.
  client.serve(generations.g2);
  const timelineApiV2 = apiReference(gen2.timeline, generations.g2);
  const aboutApiV2 = apiReference(gen2.about, generations.g2);
  await act(async () => {
    renderer.update(React.createElement(
      SnapbackProvider,
      { provider },
      React.createElement(Probe, { timelineRef: timelineApiV2, aboutRef: aboutApiV2 }),
    ));
  });
  // No throw; the changed query presents the refreshing boundary, never a
  // new-reference-over-old-binding frame and never the old contract's rows.
  assert.notEqual(timelineState.status, 'error');
  assert.notEqual(timelineState.data?.[0]?.text, 'first');
  // The unchanged sibling keeps continuity through the whole handoff.
  assert.equal(aboutState.status, 'ready');
  assert.equal(aboutState.data[0].body, 'about');

  await waitFor(
    () => provider.inspection().generationHandoff === 'ok',
    'atomic generation handoff',
  );
  assert.equal(
    activeReactBindingDeploymentIdentity(binding).bundleHash,
    generations.g2.functions.bundleHash,
    'binding admission swapped to the regenerated deployment identity',
  );
  // The new-generation store armed a fresh live subscription; serve it rows
  // under the NEW result contract.
  await waitFor(
    () => client.inspection().liveHandles.length >= 3,
    'new-generation live subscription',
  );
  const timelineHandleV2 = client.inspection().liveHandles.at(-1);
  assert.equal(timelineHandleV2.reference.implementationHash, gen2.timeline.implementationHash);
  await act(async () => {
    timelineHandleV2.emitAuthoritative([{ id: 't1', caption: 'second-generation' }]);
    await flush();
  });
  assert.equal(timelineState.status, 'ready');
  assert.equal(timelineState.data[0].caption, 'second-generation');
  assert.equal(aboutState.status, 'ready', 'continuity survived the handoff');
  assert.equal(
    client.inspection().diagnosticsChannel.snapshot().events.filter(
      (event) => event.code === 'SNAPBACK_REACT_SUBSCRIPTION_CHURN',
    ).length,
    0,
    'the mounted-provider generation handoff is not counted as hook churn',
  );

  await act(async () => { renderer.unmount(); });
  await provider.dispose();
  client.disposeDiagnostics();
  delete globalThis.__DEV__;
}

// ---------------------------------------------------------------------------
// 2. A regenerated MUTATION reference renders without throwing and its
//    invocation settles once the handoff completes (LLP 0114: admission stays
//    strict — the call admits against the swapped generation, not the old).
// ---------------------------------------------------------------------------
{
  globalThis.__DEV__ = true;
  const client = createFakeClient(generations.g1);
  const binding = await prepareReactBindingForClient(client, {
    generatedManifest: generations.g1,
  });
  const provider = createSnapbackReactProvider(binding, {
    connectionId: 'hmr-b',
    developmentHmr: { timeoutMs: 5_000, pollIntervalMs: 0 },
  });
  client.serve(generations.g2);
  let mutate = null;
  function MutationProbe() {
    mutate = useSnapbackMutation(apiReference(gen2.post, generations.g2));
    return null;
  }
  let renderer;
  await act(async () => {
    renderer = TestRenderer.create(React.createElement(
      SnapbackProvider,
      { provider },
      React.createElement(MutationProbe),
    ));
    await flush();
  });
  assert.equal(typeof mutate, 'function', 'mutation hook rendered without throwing');
  let result;
  await act(async () => {
    result = await mutate({});
  });
  assert.deepEqual(result, {
    status: 'settled',
    result: `post:${gen2.post.implementationHash}`,
  });
  assert.equal(
    client.inspection().mutations[0].ref.implementationHash,
    gen2.post.implementationHash,
    'the dispatched mutation admitted against the regenerated deployment',
  );
  await act(async () => { renderer.unmount(); });
  await provider.dispose();
  client.disposeDiagnostics();
  delete globalThis.__DEV__;
}

// ---------------------------------------------------------------------------
// 3. When the atomic handoff cannot complete (the backend never serves the
//    generation the module was built from), development falls back to a
//    CONTROLLED full reload: a clear console diagnostic, the reload seam
//    fires, hooks render an error frame — and nothing throws uncaught.
// ---------------------------------------------------------------------------
{
  globalThis.__DEV__ = true;
  const client = createFakeClient(generations.g1); // never redeploys
  const binding = await prepareReactBindingForClient(client, {
    generatedManifest: generations.g1,
  });
  const reloads = [];
  const consoleLines = [];
  const originalConsoleError = console.error;
  console.error = (...parts) => {
    const line = parts.join(' ');
    if (line.includes('SNAPBACK_REACT_HMR_REBIND_FAILED')) consoleLines.push(line);
    else originalConsoleError(...parts);
  };
  const provider = createSnapbackReactProvider(binding, {
    connectionId: 'hmr-c',
    developmentHmr: {
      timeoutMs: 30,
      pollIntervalMs: 0,
      onReloadRequired(failure) { reloads.push(failure); },
    },
  });
  let latest = null;
  function Probe() {
    latest = useSnapbackQuery(apiReference(gen2.timeline, generations.g2), {});
    return null;
  }
  let renderer;
  await act(async () => {
    renderer = TestRenderer.create(React.createElement(
      SnapbackProvider,
      { provider },
      React.createElement(Probe),
    ));
    await flush();
  });
  assert.notEqual(latest.status, 'error', 'boundary frame while the handoff is in flight');
  await waitFor(() => reloads.length === 1, 'controlled development reload');
  assert.equal(reloads[0].code, 'SNAPBACK_REACT_HMR_REBIND_FAILED');
  assert.equal(reloads[0].details.reason, 'deployment-not-current');
  assert.equal(consoleLines.length, 1, 'exactly one clear console diagnostic');
  assert.match(consoleLines[0], /SNAPBACK_REACT_HMR_REBIND_FAILED/);
  assert.match(consoleLines[0], /reload/i);
  await act(async () => { await flush(); });
  assert.equal(latest.status, 'error', 'hooks render the failure, never throw it');
  assert.equal(latest.error.code, 'SNAPBACK_REACT_HMR_REBIND_FAILED');
  assert.equal(provider.inspection().generationHandoff, 'failed');
  console.error = originalConsoleError;
  await act(async () => { renderer.unmount(); });
  await provider.dispose();
  client.disposeDiagnostics();
  delete globalThis.__DEV__;
}

// ---------------------------------------------------------------------------
// 4. Admission strictness is unchanged where recovery must not exist:
//    no positive development signal (production) and foreign/stale references
//    in development both keep the strict SNAPBACK_REACT_REFERENCE_INVALID.
// ---------------------------------------------------------------------------
{
  assert.equal(typeof globalThis.__DEV__, 'undefined');
  assert.notEqual(process.env.NODE_ENV, 'development');
  const client = createFakeClient(generations.g1);
  const binding = await prepareReactBindingForClient(client, {
    generatedManifest: generations.g1,
  });
  const provider = createSnapbackReactProvider(binding, { connectionId: 'hmr-d' });

  // Production (no positive dev signal): the regenerated reference still
  // throws strictly — HMR recovery never weakens release admission.
  assert.throws(
    () => provider.registry.descriptor(apiReference(gen2.timeline, generations.g2), {}),
    (error) => error?.code === 'SNAPBACK_REACT_REFERENCE_INVALID',
  );
  await assert.rejects(
    provider.registry.runMutation(apiReference(gen2.post, generations.g2), {}),
    (error) => error?.code === 'SNAPBACK_REACT_REFERENCE_INVALID',
  );

  globalThis.__DEV__ = true;
  // Foreign app reference: strict even in development.
  const foreign = Object.freeze({
    ...apiReference(gen1.timeline, generations.g1),
    appId: 'someone-elses-app',
    id: 'someone-elses-app:timeline',
  });
  assert.throws(
    () => provider.registry.descriptor(foreign, {}),
    (error) => error?.code === 'SNAPBACK_REACT_REFERENCE_INVALID',
  );
  // Same-generation corruption (tampered hash, no generation change): strict.
  const corrupt = Object.freeze({
    ...apiReference(gen1.timeline, generations.g1),
    implementationHash: 'sha256:tampered',
  });
  assert.throws(
    () => provider.registry.descriptor(corrupt, {}),
    (error) => error?.code === 'SNAPBACK_REACT_REFERENCE_INVALID',
  );
  // A reference with no generation stamp can never classify as regenerated.
  const { expectedGeneration: _dropped, ...unstamped } = apiReference(gen2.timeline, generations.g2);
  assert.equal(classifyRegeneratedReactReference(binding, Object.freeze(unstamped)), null);
  assert.throws(
    () => provider.registry.descriptor(Object.freeze(unstamped), {}),
    (error) => error?.code === 'SNAPBACK_REACT_REFERENCE_INVALID',
  );
  assert.equal(provider.inspection().generationHandoff, null, 'no handoff ever armed');
  await provider.dispose();
  client.disposeDiagnostics();
  delete globalThis.__DEV__;
}

await flush();
assert.deepEqual(uncaught, [], 'no uncaught exception or rejection escaped any scenario');

