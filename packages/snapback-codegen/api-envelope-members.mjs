// The codegen-owned API envelope members (LLP 0062 §5, server-composes ruling
// 2026-08-01).
//
// Codegen owns exactly two things in the envelope: the per-operation argument
// schemas and the `appBindings` declaration text. It does NOT compose the
// canonical envelope — the server does that from its own
// `PublicFunctionManifest` projection at activation, which is what makes a
// codegen/server mirror divergence structurally impossible. What codegen must
// get exactly right is the digest map binding these members, because the
// server recomputes it and refuses activation on mismatch.
//
// The canonicalization and digest domains mirror `src/api_envelope.rs` and
// `packages/snapback-app-cli/envelope.mjs`; all three are pinned to one
// another by an anchor fixture asserted in each suite.

import { createHash } from 'node:crypto';

export const API_ENVELOPE_MEMBERS_FILE = 'api-envelope.members.json';
export const DECLARATION_MEMBER_KEY = 'declaration:appBindings';
export const operationMemberKey = (stableId) => `operation:${stableId}`;

const MEMBER_DIGEST_DOMAIN = 'snapback:api-envelope-member:v1\n';

// RFC 8785 (JCS) serialization for the JSON members. Sorted keys, no
// insignificant whitespace, JSON.stringify's number forms. A value that
// cannot round-trip byte-identically must fail here rather than produce a
// digest the server will recompute differently.
export function jcsCanonical(value) {
  if (value === null) return 'null';
  const kind = typeof value;
  if (kind === 'string' || kind === 'boolean') return JSON.stringify(value);
  if (kind === 'number') {
    if (!Number.isFinite(value)) {
      throw new Error('api envelope members contain a non-finite number');
    }
    return JSON.stringify(Object.is(value, -0) ? 0 : value);
  }
  if (kind !== 'object') {
    throw new Error(`api envelope members contain a non-JSON ${kind}`);
  }
  if (Array.isArray(value)) return `[${value.map((item) => jcsCanonical(item)).join(',')}]`;
  return `{${Object.keys(value).sort()
    .map((key) => `${JSON.stringify(key)}:${jcsCanonical(value[key])}`)
    .join(',')}}`;
}

export const memberDigest = (canonical) => createHash('sha256')
  .update(MEMBER_DIGEST_DOMAIN, 'utf8')
  .update(canonical, 'utf8')
  .digest('hex');

// v1 result types are deliberately `unknown`: codegen does not yet learn
// return shapes, and the RFC names that gap rather than papering it with a
// wrong type. Live queries are the one kind with a distinct shape.
const signatureFor = (kind) => (kind === 'LiveQuery'
  ? '(args?: Record<string, unknown>) => AsyncIterable<unknown>'
  : '(args?: Record<string, unknown>) => Promise<unknown>');

/**
 * Render the app-owned binding declarations: one kind-specific callable
 * signature per exported function. Engine-owned ambient declarations never
 * ride the envelope (LLP 0062 §5's three-products rule).
 */
export function renderAppBindings(functions) {
  const members = [...functions]
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map((fn) => `  readonly ${JSON.stringify(fn.name)}: ${signatureFor(fn.kind)};`);
  return [
    '// Generated by Snapback codegen. App-owned binding declarations only.',
    'export declare const api: {',
    ...members,
    '};',
    '',
  ].join('\n');
}

/**
 * Build the members carrier from the function manifest and the already-
 * rendered operation argument schemas. Operations are keyed by stable
 * function id — selection is always by id, and the name rides only for
 * human-facing surfaces.
 */
export function buildApiEnvelopeMembers(functionManifest, operationSchemas) {
  const schemaByName = new Map(
    operationSchemas.map((schema) => [schema.file.replace(/\.args\.schema\.json$/, ''), schema.value]),
  );
  const operations = {};
  const memberDigests = {};
  for (const fn of [...functionManifest.functions].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))) {
    const argsSchema = schemaByName.get(fn.name);
    if (argsSchema === undefined) {
      throw new Error(`api envelope members: no argument schema rendered for function ${fn.name}`);
    }
    operations[fn.id] = { name: fn.name, argsSchema };
    memberDigests[operationMemberKey(fn.id)] = memberDigest(jcsCanonical(argsSchema));
  }
  const appBindings = renderAppBindings(functionManifest.functions);
  memberDigests[DECLARATION_MEMBER_KEY] = memberDigest(appBindings);
  return { operations, declarations: { appBindings }, memberDigests };
}
