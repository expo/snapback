// Shared Contract binding-module emitter.
//
// One implementation renders the drift-prone generated Contract shapes — the
// runtime-links registry, per-binding query/mutation modules, and the
// .contract-meta descriptor sidecars — for every consumer: the Snapback demo
// codegen (index.mjs) and the admin console generator
// (admin-ui/generate-contract-bindings.mjs), which had grown a drifted copy.
//
// @ref LLP 0012#versioning — one source-of-truth emitter instead of two
//   hand-synced renderers; LLP 0032 P1 folded the admin copy into this module.

export function generatedByHeader(generator = '@expo/snapback-codegen') {
  return `// Generated by ${generator}. Do not edit by hand.`;
}

export function pascal(value) {
  return value
    .replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/g, (_match, _sep, char) => char.toUpperCase())
    .replace(/[^A-Za-z0-9]/g, '');
}

function bindingLocal(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name) ? name : `__snapback${pascal(name)}`;
}

export function jsonLiteral(value) {
  return JSON.stringify(value);
}

/**
 * Whether an emitted module takes a dependency on an Exact package.
 *
 * Output-mode selection deliberately classifies rendered source rather than
 * filenames or directories: Contract-neutral runtime links and binding
 * modules share a directory with Exact-dependent metadata sidecars.
 *
 * Every module-level form that makes `@exact/*` a resolvable dependency counts,
 * not just the `import ... from` spelling the sidecars happen to use today:
 * a re-export (`export { x } from '@exact/contract'`) and a dynamic
 * `import('@exact/contract')` both fail an npm-only install just as hard.
 * Only the first is emitted-shaped today and neither is currently emitted, so
 * this is a guard against future template drift rather than live behavior.
 *
 * The bias is deliberate. A false negative puts an Exact-importing module back
 * into the neutral default set and reopens the npm-only typecheck defect this
 * classification exists to close; a false positive merely withholds a module
 * from the neutral set, which surfaces loudly as a missing artifact. When in
 * doubt, match.
 */
export function importsExactPackage(source) {
  const specifier = String.raw`['"]@exact(?:\/[^'"]*)?['"]`;
  return new RegExp(
    [
      // import x from '@exact/…' | import '@exact/…' | import type { T } from '@exact/…'
      String.raw`(?:^|\n)\s*import\s+(?:[^'"\n]*?\s+from\s+)?${specifier}\s*;?`,
      // export { x } from '@exact/…' | export * from '@exact/…'
      String.raw`(?:^|\n)\s*export\s+[^'"\n]*?\s+from\s+${specifier}\s*;?`,
      // import('@exact/…'), including `await import(...)`
      String.raw`\bimport\s*\(\s*${specifier}\s*\)`,
    ].join('|'),
    'u',
  ).test(source);
}

/**
 * The runtime-links registry module: the typed link interface plus the
 * configure/reset/get triple every generated binding delegates through.
 * `entries`: [{ name, argsType }] with argsType already rendered.
 */
export function renderRuntimeLinksModule({
  header,
  refLine,
  linksBaseName,
  errorMessage,
  entries,
}) {
  const linksName = `${linksBaseName}Links`;
  const lines = [header];
  if (refLine) lines.push(refLine);
  lines.push('', `export interface ${linksName} {`);
  for (const entry of entries) {
    lines.push(`  ${bindingLocal(entry.name) === entry.name ? entry.name : jsonLiteral(entry.name)}(args: ${entry.argsType}): unknown;`);
  }
  lines.push('}');
  lines.push('');
  lines.push(`let links: ${linksName} | null = null;`);
  lines.push('');
  lines.push(`export function configure${linksName}(next: ${linksName}): void {`);
  lines.push('  links = next;');
  lines.push('}');
  lines.push('');
  lines.push(`export function reset${linksName}(): void {`);
  lines.push('  links = null;');
  lines.push('}');
  lines.push('');
  lines.push(`export function get${linksName}(): ${linksName} {`);
  lines.push('  if (!links) {');
  lines.push(`    throw new Error('${errorMessage}');`);
  lines.push('  }');
  lines.push('  return links;');
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/**
 * One per-binding module: descriptor const, rendered Args type, and the
 * callable that delegates through the links registry.
 */
export function renderBindingModule({
  header,
  refLine,
  bindingComment,
  name,
  argsType,
  linksBaseName,
}) {
  const typeName = `${pascal(name)}Args`;
  const local = bindingLocal(name);
  const direct = local === name;
  const lines = [header];
  if (refLine) lines.push(refLine);
  if (bindingComment) lines.push(bindingComment);
  lines.push(
    '',
    `import { get${linksBaseName}Links } from './runtime-links';`,
    '',
    `export const descriptor = '${name}';`,
    `export type ${typeName} = ${argsType};`,
    '',
    `${direct ? 'export ' : ''}function ${local}(args: ${typeName}) {`,
    `  return get${linksBaseName}Links()${direct ? `.${name}` : `[${jsonLiteral(name)}]`}(args);`,
    '}',
  );
  if (!direct) lines.push(`export { ${local} as ${jsonLiteral(name)} };`);
  return `${lines.join('\n')}\n`;
}

/**
 * The .contract-meta sidecar for a query binding. `resultType` and the
 * shape entry are optional: the Snapback codegen supplies row shapes; the
 * admin bindings have no row descriptors and omit them. `extraFacts` is a
 * pre-rendered `key: value` fact list appended to the query descriptor —
 * the Snapback codegen passes the Exact 0284 §2.4 liveness facts
 * (ENG-22527); the admin bindings pass none.
 */
export function renderQueryMetaModule({
  header,
  name,
  reads,
  readMode,
  cacheKey,
  resultType = null,
  shapeName = null,
  shapeFields = null,
  extraFacts = null,
}) {
  const imports = shapeName
    ? "import { defineContractModule, query, shape } from '@exact/contract/exports';"
    : "import { defineContractModule, query } from '@exact/contract/exports';";
  const queryFacts = [
    `reads: ${jsonLiteral(reads)}`,
    `readMode: '${readMode}'`,
    `cacheKey: '${cacheKey}'`,
    ...(resultType ? [`result: '${resultType}'`] : []),
    ...(extraFacts ? [extraFacts] : []),
  ].join(', ');
  const lines = [
    header,
    imports,
    '',
    `export default defineContractModule('./${name}.query.ts', {`,
    `  ${bindingLocal(name) === name ? name : jsonLiteral(name)}: query({ ${queryFacts} }),`,
  ];
  if (shapeName) {
    lines.push(`  ${shapeName}: shape({ fields: ${jsonLiteral(shapeFields ?? {})} }),`);
  }
  lines.push('});', '');
  return lines.join('\n');
}

/** The .contract-meta sidecar for a mutation binding. */
export function renderMutationMetaModule({ header, name, effects, invalidates }) {
  return [
    header,
    "import { defineContractModule, mutation } from '@exact/contract/exports';",
    '',
    `export default defineContractModule('./${name}.mutation.ts', {`,
    `  ${bindingLocal(name) === name ? name : jsonLiteral(name)}: mutation({ effects: ${jsonLiteral(effects)}, invalidates: ${jsonLiteral(invalidates)} }),`,
    '});',
    '',
  ].join('\n');
}
