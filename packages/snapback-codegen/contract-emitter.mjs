// Shared Contract binding-module emitter.
//
// One implementation renders the drift-prone generated Contract shapes — the
// runtime-links registry, per-binding query/mutation modules, and the
// .contract-meta descriptor sidecars — for every consumer: the Snapback demo
// codegen (index.mjs) and the admin console generator
// (admin-ui/generate-contract-bindings.mjs), which had grown a drifted copy.
//
// @ref LLP 0012#versioning — one source-of-truth emitter instead of two
//   hand-synced renderers; LLP 0032 P1 folded the admin copy into this module.

export function generatedByHeader(generator = '@snapback/codegen') {
  return `// Generated by ${generator}. Do not edit by hand.`;
}

export function pascal(value) {
  return value
    .replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/g, (_match, _sep, char) => char.toUpperCase())
    .replace(/[^A-Za-z0-9]/g, '');
}

export function jsonLiteral(value) {
  return JSON.stringify(value);
}

/**
 * The runtime-links registry module: the typed link interface plus the
 * configure/reset/get triple every generated binding delegates through.
 * `entries`: [{ name, argsType }] with argsType already rendered.
 */
export function renderRuntimeLinksModule({
  header,
  refLine,
  linksBaseName,
  errorMessage,
  entries,
}) {
  const linksName = `${linksBaseName}Links`;
  const lines = [header];
  if (refLine) lines.push(refLine);
  lines.push('', `export interface ${linksName} {`);
  for (const entry of entries) {
    lines.push(`  ${entry.name}(args: ${entry.argsType}): unknown;`);
  }
  lines.push('}');
  lines.push('');
  lines.push(`let links: ${linksName} | null = null;`);
  lines.push('');
  lines.push(`export function configure${linksName}(next: ${linksName}): void {`);
  lines.push('  links = next;');
  lines.push('}');
  lines.push('');
  lines.push(`export function reset${linksName}(): void {`);
  lines.push('  links = null;');
  lines.push('}');
  lines.push('');
  lines.push(`export function get${linksName}(): ${linksName} {`);
  lines.push('  if (!links) {');
  lines.push(`    throw new Error('${errorMessage}');`);
  lines.push('  }');
  lines.push('  return links;');
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/**
 * One per-binding module: descriptor const, rendered Args type, and the
 * callable that delegates through the links registry.
 */
export function renderBindingModule({
  header,
  refLine,
  bindingComment,
  name,
  argsType,
  linksBaseName,
}) {
  const typeName = `${pascal(name)}Args`;
  const lines = [header];
  if (refLine) lines.push(refLine);
  if (bindingComment) lines.push(bindingComment);
  lines.push(
    '',
    `import { get${linksBaseName}Links } from './runtime-links';`,
    '',
    `export const descriptor = '${name}';`,
    `export type ${typeName} = ${argsType};`,
    '',
    `export function ${name}(args: ${typeName}) {`,
    `  return get${linksBaseName}Links().${name}(args);`,
    '}',
  );
  return `${lines.join('\n')}\n`;
}

/**
 * The .contract-meta sidecar for a query binding. `resultType` and the
 * shape entry are optional: the Snapback codegen supplies row shapes; the
 * admin bindings have no row descriptors and omit them.
 */
export function renderQueryMetaModule({
  header,
  name,
  reads,
  readMode,
  cacheKey,
  resultType = null,
  shapeName = null,
  shapeFields = null,
}) {
  const imports = shapeName
    ? "import { defineContractModule, query, shape } from '@exact/contract/exports';"
    : "import { defineContractModule, query } from '@exact/contract/exports';";
  const queryFacts = [
    `reads: ${jsonLiteral(reads)}`,
    `readMode: '${readMode}'`,
    `cacheKey: '${cacheKey}'`,
    ...(resultType ? [`result: '${resultType}'`] : []),
  ].join(', ');
  const lines = [
    header,
    imports,
    '',
    `export default defineContractModule('./${name}.query.ts', {`,
    `  ${name}: query({ ${queryFacts} }),`,
  ];
  if (shapeName) {
    lines.push(`  ${shapeName}: shape({ fields: ${jsonLiteral(shapeFields ?? {})} }),`);
  }
  lines.push('});', '');
  return lines.join('\n');
}

/** The .contract-meta sidecar for a mutation binding. */
export function renderMutationMetaModule({ header, name, effects, invalidates }) {
  return [
    header,
    "import { defineContractModule, mutation } from '@exact/contract/exports';",
    '',
    `export default defineContractModule('./${name}.mutation.ts', {`,
    `  ${name}: mutation({ effects: ${jsonLiteral(effects)}, invalidates: ${jsonLiteral(invalidates)} }),`,
    '});',
    '',
  ].join('\n');
}
