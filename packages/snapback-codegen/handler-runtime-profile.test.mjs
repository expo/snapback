import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, test } from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { generate } from './index.mjs';
import {
  handlerRuleForCode,
  INLINE_HANDLER_RULES,
} from './handler-runtime-profile.mjs';

const packageRoot = dirname(fileURLToPath(import.meta.url));
const defineUrl = pathToFileURL(join(packageRoot, 'define.mjs')).href;
const roots = [];

function backend(functions) {
  const root = mkdtempSync(join(tmpdir(), 'snapback-handler-profile-'));
  roots.push(root);
  writeFileSync(join(root, 'schema.mjs'), `
import { defineSchema, defineTable, v } from '${defineUrl}';
export default defineSchema({
  todos: defineTable({ title: v.string() })
    .visibility({ kind: 'public-read' })
    .sync(),
});
`);
  writeFileSync(join(root, 'functions.mjs'), functions);
  return root;
}

function treeDigest(root) {
  const hash = createHash('sha256');
  const visit = (directory, prefix = '') => {
    for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) visit(path, relative);
      else {
        hash.update(relative);
        hash.update(readFileSync(path));
      }
    }
  };
  visit(root);
  return hash.digest('hex');
}

after(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
});

test('emits the current handler profile and --check preserves generated bytes', async () => {
  const valid = backend(`
import { defineJsQuery } from '${defineUrl}';
function trimTitle(value) { return value.trim(); }
export const listTodos = defineJsQuery({
  args: {}, reads: ['todos'],
  handler: async () => [{ title: trimTitle('demo') }],
});
`);
  const generated = await generate(valid);
  assert.equal(generated.ok, true, JSON.stringify(generated.diagnostics));
  const profilePath = join(valid, 'generated', 'handler-runtime-profile.v1.json');
  assert.equal(existsSync(profilePath), true);
  const profile = JSON.parse(readFileSync(profilePath, 'utf8'));
  assert.equal(profile.schemaVersion, 'snapback.handler-runtime-profile.v1');
  assert.deepEqual(profile.moduleGraph.admittedSpecifiers, []);
  assert.deepEqual(profile.computedAccess.forbiddenReflectionProperties, [...INLINE_HANDLER_RULES.reflectionPropertyNames].sort());
  assert.equal(profile.operations[0].selectedProfile, 'inline-handler-same-file-helpers-v2');
  assert.equal(profile.operations[0].selectionReason, 'legacy-profile');
  assert.equal(profile.moduleGraph.identityEvidence.canonicalExecutableDigestField, 'implementationHash');
  assert.equal(profile.moduleGraph.identityEvidence.rawEvidenceDigestField, 'authoredSourceHash');
  assert.equal(
    profile.moduleGraph.graphRecordSchema.schemaVersion,
    'snapback.handler-graph-record.v1',
  );
  assert.deepEqual(profile.moduleGraph.graphRecordSchema.digestFields, {
    canonicalExecutableAstDigest: 'canonical-executable',
    rawSourceEvidenceDigest: 'raw-source-evidence',
  });
  assert.equal(
    profile.moduleGraph.graphRecordSchema.sourceSnapshot.attestedReread,
    'not-applicable-while-relative-imports-are-not-admitted',
  );
  assert.equal(profile.moduleGraph.records.length, 1);
  assert.equal(profile.moduleGraph.records[0].root.normalizedTarget, 'functions.mjs');
  assert.equal(profile.moduleGraph.records[0].edges[0].resolution, 'self');
  assert.equal(profile.globals.Query.handlerForms.inline.timers, 'unavailable');
  assert.equal(
    handlerRuleForCode('BUNDLE_UNSUPPORTED_IMPORT').phase,
    'static-admission',
  );
  assert.equal(
    handlerRuleForCode('SNAPBACK_HANDLER_AMBIENT_CAPABILITY_DENIED').phase,
    'runtime-check',
  );
  assert.match(
    handlerRuleForCode('BUNDLE_UNSUPPORTED_IMPORT').guideAnchor,
    /^\/_snapback\/guide\/backend\/handler-runtime\.md#/u,
  );
  assert.equal(
    handlerRuleForCode('SNAPBACK_CODEGEN_FAMILIAR_RETURNS_UNLOWERABLE').guideAnchor,
    '/_snapback/guide/backend/familiar-profile.md#translate-the-familiar-handler-dialect',
  );
  const profileRecord = generated.artifactIndex.files.find(({ path }) => path === 'handler-runtime-profile.v1.json');
  assert.equal(profileRecord.logicalKind, 'handler-runtime-profile');
  assert.equal(profileRecord.consumer, 'developer-tooling');

  const before = treeDigest(join(valid, 'generated'));
  const checked = await generate(valid, { check: true });
  assert.equal(checked.ok, true, JSON.stringify(checked.diagnostics));
  assert.equal(checked.checked, true);
  assert.equal(checked.emitted, false);
  assert.equal(checked.cacheGraphRoot, null);
  assert.equal(treeDigest(join(valid, 'generated')), before, '--check changed generated output');
});

test('attributes an unexported top-level operation', async () => {
  const unexported = backend(`
import { defineQuery } from '${defineUrl}';
const hiddenTodos = defineQuery({ table: 'todos', args: {} });
`);
  const hiddenResult = await generate(unexported, { check: true });
  assert.equal(hiddenResult.ok, false);
  const hidden = hiddenResult.diagnostics.find(({ code }) => code === 'SNAPBACK_CODEGEN_DEFINITION_NOT_EXPORTED');
  assert.equal(hidden.binding, 'hiddenTodos');
  assert.equal(hidden.definitionPath, 'hiddenTodos');
  assert.equal(hidden.sourceSpan.file, 'functions.mjs');
  assert.match(hidden.details.remediation, /export const hiddenTodos/u);

  const defaultExport = backend(`
import { defineQuery } from '${defineUrl}';
const defaultTodos = defineQuery({ table: 'todos', args: {} });
export default defaultTodos;
`);
  const defaultResult = await generate(defaultExport, { check: true });
  assert.equal(
    defaultResult.diagnostics.some(({ code }) => code === 'SNAPBACK_CODEGEN_DEFINITION_NOT_EXPORTED'),
    false,
    JSON.stringify(defaultResult.diagnostics),
  );
});

test('attributes a nested unserializable definition value', async () => {
  const nested = backend(`
import { defineMutation, insert, lit } from '${defineUrl}';
export const createTodo = defineMutation({
  args: {},
  plan: insert('todos', { title: lit({ media: { optional: () => false } }) }),
});
`);
  const nestedResult = await generate(nested, { check: true });
  assert.equal(nestedResult.ok, false);
  const unserializable = nestedResult.diagnostics.find(({ code }) => code === 'SNAPBACK_CODEGEN_DEFINITION_VALUE_UNSERIALIZABLE');
  assert.match(unserializable.definitionPath, /^createTodo\.plan\..*\.media\.optional$/u);
  assert.deepEqual(unserializable.details.definitionPath.slice(-2), ['media', 'optional']);
  assert.equal(unserializable.sourceSpan.file, 'functions.mjs');
});

test('attributes an optional:false-style invalid asset option', async () => {
  const invalidOption = backend(`
import { defineAssetUpload, defineCommand, defineMutation, insert, lit, v } from '${defineUrl}';
export const imageUpload = defineAssetUpload({
  args: {}, auth: 'authenticated',
  accept: { mediaTypes: ['application/octet-stream'], maxBytes: 1024 },
  delivery: { kind: 'private-strict' },
  authorize: async (ctx) => ({ owner: ctx.auth.userId }),
});
export const sendMessage = defineMutation({
  auth: 'authenticated', args: { image: v.optional(v.assetRef({ upload: 'imageUpload' })) },
  plan: insert('todos', { title: lit('sent') }),
});
export const sendPhoto = defineCommand({
  mutation: sendMessage,
  assets: { image: { intent: imageUpload, mutationArg: 'image', optional: 'false' } },
});
`);
  const optionResult = await generate(invalidOption, { check: true });
  assert.equal(optionResult.ok, false);
  const option = optionResult.diagnostics.find(({ definitionPath }) => definitionPath === 'sendPhoto.assets.image.optional');
  assert(option, JSON.stringify(optionResult.diagnostics));
  assert.equal(option.sourceSpan.file, 'functions.mjs');
  assert.match(option.message, /optional must be boolean/u);
});
