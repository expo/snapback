#!/usr/bin/env python3
"""Focused source-scan policy regression for the LLP ref checker."""

import importlib.machinery
import importlib.util
import os
import tempfile
import unittest
from unittest import mock


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = "@" + "ref"
loader = importlib.machinery.SourceFileLoader("snapback_ref_check", os.path.join(ROOT, "ref-check"))
spec = importlib.util.spec_from_loader(loader.name, loader)
ref_check = importlib.util.module_from_spec(spec)
loader.exec_module(ref_check)


class RefCheckScanPolicyTest(unittest.TestCase):
    def test_repository_has_no_unchecked_shorthand_refs(self):
        report, _, _, _ = ref_check.check(ROOT)
        self.assertEqual(report.infos, [])

    def test_build_outputs_and_source_maps_do_not_affect_validation_or_counts(self):
        with tempfile.TemporaryDirectory() as root:
            os.makedirs(os.path.join(root, "llp"))
            with open(os.path.join(root, "llp", "0000-fixture.explainer.md"), "w", encoding="utf-8") as handle:
                handle.write(
                    "# Fixture\n\n"
                    "**Type:** Explainer\n"
                    "**Status:** Draft\n"
                    "**Systems:** Testing\n"
                    "**Author:** Test\n"
                    "**Date:** 2026-07-12\n\n"
                    "## Contract\n"
                )
            os.makedirs(os.path.join(root, "src"))
            with open(os.path.join(root, "src", "app.js"), "w", encoding="utf-8") as handle:
                handle.write(f"// {REF} LLP 0000#contract — valid source ref\n")

            # Both contain broken refs, but neither is authored source.
            os.makedirs(os.path.join(root, "target", "debug", ".fingerprint"))
            with open(os.path.join(root, "target", "debug", ".fingerprint", "output"), "w", encoding="utf-8") as handle:
                handle.write(f"// {REF} LLP 9999#missing — build output\n")
            with open(os.path.join(root, "bundle.js.map"), "w", encoding="utf-8") as handle:
                handle.write(f"// {REF} LLP 9999#missing — generated source map\n")

            report, file_count, ref_count, doc_count = ref_check.check(root)
            self.assertEqual(report.errors, [])
            self.assertEqual(doc_count, 1)
            self.assertEqual(ref_count, 1)
            self.assertEqual(file_count, 2)  # one LLP document + one JS source

    def test_generated_marked_files_are_not_authored_source(self):
        with tempfile.TemporaryDirectory() as root:
            os.makedirs(os.path.join(root, "llp"))
            with open(os.path.join(root, "llp", "0000-fixture.explainer.md"), "w", encoding="utf-8") as handle:
                handle.write(
                    "# Fixture\n\n"
                    "**Type:** Explainer\n"
                    "**Status:** Draft\n"
                    "**Systems:** Testing\n"
                    "**Author:** Test\n"
                    "**Date:** 2026-07-12\n\n"
                )
            os.makedirs(os.path.join(root, "src"))
            # A committed generated sidecar citing another repo's corpus:
            # broken-here numbers and unmapped shorthand must not report.
            with open(os.path.join(root, "src", "meta.generated.ts"), "w", encoding="utf-8") as handle:
                handle.write(
                    "// @generated by another repo's tooling — do not edit by hand.\n"
                    f"// {REF} LLP 9999 R4 (sidecar generation); LLP 8888 Slice A/B.\n"
                )

            report, file_count, ref_count, doc_count = ref_check.check(root)
            self.assertEqual(report.errors, [])
            self.assertEqual(report.infos, [])
            self.assertEqual(doc_count, 1)
            self.assertEqual(ref_count, 0)
            self.assertEqual(file_count, 1)  # the LLP document only


def write_llp(root, name, *, doc_type="Explainer", status="Draft", body="## Contract\n"):
    os.makedirs(os.path.join(root, "llp"), exist_ok=True)
    path = os.path.join(root, "llp", name)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(
            f"# Fixture\n\n"
            f"**Type:** {doc_type}\n"
            f"**Status:** {status}\n"
            f"**Systems:** Testing\n"
            f"**Author:** Test\n"
            f"**Date:** 2026-08-25\n\n"
            f"{body}"
        )
    return path


class RefCheckLlpV2Test(unittest.TestCase):
    def test_plain_text_status_is_reported_as_missing_metadata(self):
        with tempfile.TemporaryDirectory() as root:
            path = write_llp(root, "0000-fixture.explainer.md")
            with open(path, encoding="utf-8") as handle:
                source = handle.read()
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(source.replace("**Status:** Draft", "Status: Draft"))

            report, _, _, doc_count = ref_check.check(root)

            self.assertEqual(doc_count, 1)
            self.assertIn(
                "llp/0000-fixture.explainer.md: missing required metadata field **Status:**",
                report.errors,
            )

    def test_one_unparseable_document_does_not_abort_the_corpus(self):
        with tempfile.TemporaryDirectory() as root:
            write_llp(root, "0000-bad.explainer.md", body="## Force parser failure\n")
            write_llp(root, "0001-good.explainer.md")
            original_md_headings = ref_check.md_headings

            def fail_one_document(text):
                if "Force parser failure" in text:
                    raise ValueError("fixture parser failure")
                return original_md_headings(text)

            with mock.patch.object(ref_check, "md_headings", side_effect=fail_one_document):
                report, _, _, doc_count = ref_check.check(root)

            self.assertEqual(doc_count, 1)
            self.assertTrue(any(
                error.startswith("llp/0000-bad.explainer.md: could not parse LLP document")
                and "fixture parser failure" in error
                for error in report.errors
            ))
            self.assertFalse(any("0001-good" in error for error in report.errors))

    def test_overlay_relative_symlink_and_path_file_are_accepted(self):
        with tempfile.TemporaryDirectory() as root:
            write_llp(root, "0000-fixture.explainer.md", status="Active")
            os.makedirs(os.path.join(root, "llp", "foundation"))
            os.makedirs(os.path.join(root, "llp", "current"))
            os.symlink(
                "../0000-fixture.explainer.md",
                os.path.join(root, "llp", "foundation", "0000-fixture.explainer.md"),
            )
            with open(
                os.path.join(root, "llp", "current", "0000-fixture.explainer.md"),
                "w",
                encoding="utf-8",
            ) as handle:
                handle.write("../0000-fixture.explainer.md\n")
            report, _, _, doc_count = ref_check.check(root)
            self.assertEqual(report.errors, [])
            self.assertEqual(doc_count, 1)

    def test_foundation_rejects_non_active_and_tombstoned_overlay_membership(self):
        with tempfile.TemporaryDirectory() as root:
            write_llp(root, "0000-fixture.explainer.md", status="Draft")
            write_llp(root, "0001-old.rfc.md", status="Tombstoned", doc_type="RFC")
            os.makedirs(os.path.join(root, "llp", "foundation"))
            os.makedirs(os.path.join(root, "llp", "current"))
            os.symlink(
                "../0000-fixture.explainer.md",
                os.path.join(root, "llp", "foundation", "0000-fixture.explainer.md"),
            )
            os.symlink(
                "../0001-old.rfc.md",
                os.path.join(root, "llp", "current", "0001-old.rfc.md"),
            )
            report, _, _, _ = ref_check.check(root)
            self.assertTrue(any("foundation entries must be Active" in error for error in report.errors))
            self.assertTrue(any("Tombstoned LLP 0001 may not appear" in error for error in report.errors))

    def test_sub_llp_requires_parent_and_dotted_refs_resolve(self):
        with tempfile.TemporaryDirectory() as root:
            write_llp(root, "0000-fixture.explainer.md", status="Active")
            write_llp(
                root,
                "0000.000-child.spec.md",
                doc_type="Spec",
                status="Draft",
                body="## Tokens\n",
            )
            os.makedirs(os.path.join(root, "src"))
            with open(os.path.join(root, "src", "app.js"), "w", encoding="utf-8") as handle:
                handle.write(f"// {REF} LLP 0000.000#tokens — dotted child\n")
                handle.write(f"// {REF} LLP 0011.00 — malformed child\n")
            report, _, ref_count, doc_count = ref_check.check(root)
            self.assertEqual(doc_count, 2)
            self.assertEqual(ref_count, 2)
            self.assertFalse(any("no parent" in error for error in report.errors))
            self.assertTrue(any("malformed LLP target" in error for error in report.errors))

            write_llp(root, "0012.000-orphan.spec.md", doc_type="Spec")
            report, _, _, _ = ref_check.check(root)
            self.assertTrue(any("sub-LLP 0012.000 has no parent" in error for error in report.errors))

    def test_overlay_directory_does_not_duplicate_numbers(self):
        with tempfile.TemporaryDirectory() as root:
            write_llp(root, "0000-fixture.explainer.md", status="Active")
            os.makedirs(os.path.join(root, "llp", "foundation"))
            os.symlink(
                "../0000-fixture.explainer.md",
                os.path.join(root, "llp", "foundation", "0000-fixture.explainer.md"),
            )
            report, _, _, doc_count = ref_check.check(root)
            self.assertEqual(report.errors, [])
            self.assertEqual(doc_count, 1)


if __name__ == "__main__":
    unittest.main()
