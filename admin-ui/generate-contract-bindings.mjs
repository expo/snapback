// Generate the admin Contract binding modules from contract-bindings.mjs.
//
// This is deliberately small and admin-specific. The important LLP 0021 property
// is that runtime links and descriptor sidecars are generated from one binding
// list, so the admin surface does not drift one hand-written file at a time.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { adminContractBindings } from './contract-bindings.mjs';

const here = dirname(fileURLToPath(import.meta.url));

export function generateAdminContractBindings({ root = here } = {}) {
  const outDir = join(resolve(root), 'generated', 'contract');
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  const files = [
    {
      file: 'runtime-links.ts',
      source: renderRuntimeLinks(adminContractBindings),
    },
  ];

  for (const binding of adminContractBindings) {
    const suffix = binding.kind === 'query' ? 'query' : 'mutation';
    files.push({
      file: `${binding.name}.${suffix}.ts`,
      source: renderBindingModule(binding),
    });
    files.push({
      file: `${binding.name}.${suffix}.contract-meta.ts`,
      source: binding.kind === 'query'
        ? renderQueryMeta(binding)
        : renderMutationMeta(binding),
    });
  }

  for (const { file, source } of files) {
    writeFileSync(join(outDir, file), source);
  }
  return { outDir, files: files.map((entry) => entry.file) };
}

function renderRuntimeLinks(bindings) {
  const lines = [
    '// Generated by admin-ui/generate-contract-bindings.mjs. Do not edit by hand.',
    '// @ref LLP 0021#phase-4-move-admin-and-demo-surfaces-onto-the-adapter - admin runtime links are generated from one binding list.',
    '',
    'export interface AdminContractLinks {',
  ];
  for (const binding of bindings) {
    lines.push(`  ${binding.name}(args: ${typeForArgs(binding.args)}): unknown;`);
  }
  lines.push('}');
  lines.push('');
  lines.push('let links: AdminContractLinks | null = null;');
  lines.push('');
  lines.push('export function configureAdminContractLinks(next: AdminContractLinks): void {');
  lines.push('  links = next;');
  lines.push('}');
  lines.push('');
  lines.push('export function resetAdminContractLinks(): void {');
  lines.push('  links = null;');
  lines.push('}');
  lines.push('');
  lines.push('export function getAdminContractLinks(): AdminContractLinks {');
  lines.push('  if (!links) {');
  lines.push("    throw new Error('Admin Contract links were used before the bridge was configured.');");
  lines.push('  }');
  lines.push('  return links;');
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

function renderBindingModule(binding) {
  const suffix = binding.kind === 'query' ? 'query' : 'mutation';
  const typeName = `${pascal(binding.name)}Args`;
  return [
    '// Generated by admin-ui/generate-contract-bindings.mjs. Do not edit by hand.',
    '// @ref LLP 0021#phase-4-move-admin-and-demo-surfaces-onto-the-adapter - per-binding admin Contract modules import ordinary query/mutation symbols.',
    `// Admin ${suffix} binding for ${binding.name}.`,
    '',
    "import { getAdminContractLinks } from './runtime-links';",
    '',
    `export const descriptor = '${binding.name}';`,
    `export type ${typeName} = ${typeForArgs(binding.args)};`,
    '',
    `export function ${binding.name}(args: ${typeName}) {`,
    `  return getAdminContractLinks().${binding.name}(args);`,
    '}',
    '',
  ].join('\n');
}

function renderQueryMeta(binding) {
  return [
    '// Generated by admin-ui/generate-contract-bindings.mjs. Do not edit by hand.',
    "import { defineContractModule, query } from '@exact/contract/exports';",
    '',
    `export default defineContractModule('./${binding.name}.query.ts', {`,
    `  ${binding.name}: query({ reads: ${jsonLiteral(binding.reads)}, readMode: '${binding.readMode}', cacheKey: '${binding.cacheKey}' }),`,
    '});',
    '',
  ].join('\n');
}

function renderMutationMeta(binding) {
  return [
    '// Generated by admin-ui/generate-contract-bindings.mjs. Do not edit by hand.',
    "import { defineContractModule, mutation } from '@exact/contract/exports';",
    '',
    `export default defineContractModule('./${binding.name}.mutation.ts', {`,
    `  ${binding.name}: mutation({ effects: ${jsonLiteral(binding.effects)}, invalidates: ${jsonLiteral(binding.invalidates)} }),`,
    '});',
    '',
  ].join('\n');
}

function typeForArgs(args) {
  const entries = Object.entries(args ?? {});
  if (entries.length === 0) return 'Record<string, never>';
  return `{ ${entries.map(([name, type]) => `${name}: ${typeForPrimitive(type)}`).join('; ')} }`;
}

function typeForPrimitive(type) {
  return { string: 'string', number: 'number', boolean: 'boolean' }[type] ?? 'unknown';
}

function pascal(value) {
  return value
    .replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/g, (_match, _sep, char) => char.toUpperCase())
    .replace(/[^A-Za-z0-9]/g, '');
}

function jsonLiteral(value) {
  return JSON.stringify(value);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generateAdminContractBindings();
  console.log(`admin-ui: generated Contract bindings -> ${result.outDir}`);
}
